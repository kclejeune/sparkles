#!/usr/bin/env python3
"""Writes crates/sparkles-core/src/text/dict/java_tables.rs, the Java character properties that
Lucene's Kuromoji and Nori tokenizers read, for the dictionary analyzers.

The tokenizers look at UTF-16 code units with Java's Character.getType,
Character.isDigit and Character.UnicodeScript, which Java 21 takes from Unicode 15.0.
This script downloads Unicode 15.0's DerivedGeneralCategory.txt and Scripts.txt, checks
their SHA-256, and writes, for the code points below 0x10000, ranges with four flags
(punctuation as the tokenizers define it, Zs, Mn and Nd) and a script number.

    scripts/text-lucene-compare/java-tables.py [CACHE_DIR]
"""

import hashlib
import os
import re
import sys
import tempfile
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "crates/sparkles-core/src/text/dict/java_tables.rs")
FILES = {
    "DerivedGeneralCategory.txt": (
        "https://www.unicode.org/Public/15.0.0/ucd/extracted/DerivedGeneralCategory.txt",
        "fe29a45c0882500e591140aaa5c4f5067e6a5d746806148af34400c48b9c06f9",
    ),
    "Scripts.txt": (
        "https://www.unicode.org/Public/15.0.0/ucd/Scripts.txt",
        "cca85d830f46aece2e7c1459ef1249993dca8f2e46d51e869255be140d7ea4b0",
    ),
}
# Character.getType values that Kuromoji's and Nori's isPunctuation accept
PUNCT = {"Zs", "Zl", "Zp", "Cc", "Cf", "Pd", "Ps", "Pe", "Pc", "Po", "Sm", "Sc", "Sk", "So", "Pi", "Pf"}


def fetch(cache, name):
    url, sha = FILES[name]
    path = os.path.join(cache, name)
    if not os.path.exists(path):
        with urllib.request.urlopen(url, timeout=60) as r:
            data = r.read()
        with open(path, "wb") as f:
            f.write(data)
    data = open(path, "rb").read()
    got = hashlib.sha256(data).hexdigest()
    if got != sha:
        sys.exit(f"{name}: SHA-256 {got}, expected {sha}")
    return data.decode("utf-8")


def rows(text):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = [f.strip() for f in line.split(";")[:2]]
        m = re.fullmatch(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?", cps)
        first = int(m.group(1), 16)
        last = int(m.group(2), 16) if m.group(2) else first
        yield first, min(last, 0xFFFF), value


def main():
    cache = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
    os.makedirs(cache, exist_ok=True)
    props = [0] * 0x10000
    for first, last, gc in rows(fetch(cache, "DerivedGeneralCategory.txt")):
        bits = (1 if gc in PUNCT else 0) | (2 if gc == "Zs" else 0) | (4 if gc == "Mn" else 0)
        bits |= 8 if gc == "Nd" else 0
        for cp in range(first, last + 1):
            props[cp] |= bits
    names = ["Unknown", "Common", "Inherited"]
    for first, last, sc in rows(fetch(cache, "Scripts.txt")):
        if sc not in names:
            names.append(sc)
        for cp in range(first, last + 1):
            props[cp] |= names.index(sc) << 8
    ranges = []
    for cp, bits in enumerate(props):
        if ranges and ranges[-1][2] == bits:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, bits])
    with open(OUT, "w") as f:
        f.write(
            "// @generated by scripts/text-lucene-compare/java-tables.py from the Unicode\n"
            "// Character Database 15.0.0 (DerivedGeneralCategory.txt, Scripts.txt), under the\n"
            "// Unicode License. Do not edit.\n\n"
            "//! Java's character properties of the code points below 0x10000, as Java 21 has them:\n"
            "//! for each range, punctuation as Kuromoji and Nori define it (bit 0), Zs (bit 1), Mn\n"
            "//! (bit 2), Nd (bit 3), and the script's number (bits 8 to 15; 0 is Unknown, 1\n"
            "//! Common and 2 Inherited).\n\n"
            f"pub(super) static RANGES: [(u16, u16, u16); {len(ranges)}] = [\n"
        )
        for a, b, bits in ranges:
            f.write(f"    (0x{a:X}, 0x{b:X}, 0x{bits:X}),\n")
        f.write("];\n")
    print(f"{OUT}: {len(ranges)} ranges, {len(names)} scripts")


if __name__ == "__main__":
    main()
