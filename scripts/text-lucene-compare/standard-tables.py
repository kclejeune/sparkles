#!/usr/bin/env python3
"""Writes crates/sparkles-core/src/text/standard_tables.rs, the character properties of
the tokenizer that follows Lucene's StandardTokenizer.

Lucene 9.11.1's StandardTokenizer is generated by JFlex from a grammar that reads
Unicode 12.1's Word_Break, Script and Line_Break properties and the emoji properties of
UTS #51 version 12.1. This script downloads those data files from unicode.org, checks
their SHA-256 against the pinned values, and writes a sorted table of code point ranges
with the properties packed into 16 bits.

    scripts/text-lucene-compare/standard-tables.py [CACHE_DIR]

CACHE_DIR keeps the downloaded files (default: a temporary directory).
"""

import hashlib
import os
import re
import sys
import tempfile
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "crates/sparkles-core/src/text/standard_tables.rs")

FILES = {
    "WordBreakProperty.txt": (
        "https://www.unicode.org/Public/12.1.0/ucd/auxiliary/WordBreakProperty.txt",
        "f221f89fe3bb3becc00de726d5694c4b7f464c316baff6d339b2ff3900bcb96c",
    ),
    "Scripts.txt": (
        "https://www.unicode.org/Public/12.1.0/ucd/Scripts.txt",
        "e6313a8edfd24f36c7a006fbcf1d1b7245b5dd009c6dde80441f0da08b822c43",
    ),
    "LineBreak.txt": (
        "https://www.unicode.org/Public/12.1.0/ucd/LineBreak.txt",
        "961f842fc70b5afd1d82c6645e68c10d1f701382aed38ae38cb2ff27f671903c",
    ),
    "emoji-data.txt": (
        "https://www.unicode.org/Public/emoji/12.1/emoji-data.txt",
        "700c7983a94fd9b3f6b00307c341641bdada4b57db587c968eda62b7eadb6728",
    ),
}

# The Word_Break values the grammar uses, in the order of standard.rs's `Wb`.
WB = [
    "ALetter",
    "Hebrew_Letter",
    "Numeric",
    "Katakana",
    "MidLetter",
    "MidNumLet",
    "Single_Quote",
    "MidNum",
    "ExtendNumLet",
    "Double_Quote",
    "Regional_Indicator",
    "Format",
    "Extend",
    "ZWJ",
]
SCRIPTS = {"Han": 1, "Hiragana": 2, "Hangul": 3}
SA = 1 << 6
EMOJI = {
    "Emoji": 1 << 7,
    "Emoji_Modifier": 1 << 8,
    "Emoji_Modifier_Base": 1 << 9,
    "Extended_Pictographic": 1 << 10,
}


def fetch(cache, name):
    url, sha = FILES[name]
    path = os.path.join(cache, name)
    if not os.path.exists(path):
        with urllib.request.urlopen(url, timeout=60) as r:
            data = r.read()
        with open(path, "wb") as f:
            f.write(data)
    data = open(path, "rb").read()
    got = hashlib.sha256(data).hexdigest()
    if got != sha:
        sys.exit(f"{name}: SHA-256 {got}, expected {sha}")
    return data.decode("utf-8")


def rows(text):
    """(first, last, value) for each data line of a UCD file."""
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = [f.strip() for f in line.split(";")[:2]]
        m = re.fullmatch(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?", cps)
        first = int(m.group(1), 16)
        last = int(m.group(2), 16) if m.group(2) else first
        yield first, last, value


def main():
    cache = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
    os.makedirs(cache, exist_ok=True)
    props = {}

    def set_bits(first, last, mask, bits):
        for cp in range(first, last + 1):
            props[cp] = (props.get(cp, 0) & ~mask) | bits

    for first, last, v in rows(fetch(cache, "WordBreakProperty.txt")):
        if v in WB:
            set_bits(first, last, 0xF, WB.index(v) + 1)
    for first, last, v in rows(fetch(cache, "Scripts.txt")):
        if v in SCRIPTS:
            set_bits(first, last, 0x30, SCRIPTS[v] << 4)
    for first, last, v in rows(fetch(cache, "LineBreak.txt")):
        if v == "SA":
            set_bits(first, last, SA, SA)
    for first, last, v in rows(fetch(cache, "emoji-data.txt")):
        if v in EMOJI:
            set_bits(first, last, EMOJI[v], EMOJI[v])

    ranges = []
    for cp in sorted(props):
        bits = props[cp]
        if bits == 0:
            continue
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == bits:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, bits])

    with open(OUT, "w") as f:
        f.write(
            "// @generated by scripts/text-lucene-compare/standard-tables.py from the Unicode\n"
            "// Character Database 12.1.0 (WordBreakProperty.txt, Scripts.txt, LineBreak.txt)\n"
            "// and the emoji data of UTS #51 version 12.1 (emoji-data.txt), under the Unicode\n"
            "// License. Do not edit.\n\n"
            "//! The character properties of [`super::standard`]: for each range of code points\n"
            "//! with any, the Word_Break value (bits 0 to 3, `Wb`), the script (bits 4 and 5:\n"
            "//! Han, Hiragana or Hangul), Line_Break=Complex_Context (bit 6), and Emoji,\n"
            "//! Emoji_Modifier, Emoji_Modifier_Base and Extended_Pictographic (bits 7 to 10).\n\n"
            f"pub(super) static RANGES: [(u32, u32, u16); {len(ranges)}] = [\n"
        )
        for a, b, bits in ranges:
            f.write(f"    (0x{a:X}, 0x{b:X}, 0x{bits:X}),\n")
        f.write("];\n")
    print(f"{OUT}: {len(ranges)} ranges")


if __name__ == "__main__":
    main()
