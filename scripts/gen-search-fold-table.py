#!/usr/bin/env python3
"""Write the fold table of the ontology entity search to stdout:

    python3 scripts/gen-search-fold-table.py > crates/sparkles/src/handles/ontology/search/fold_table.rs
"""
import unicodedata, sys
ranges = [(0x00A0,0x024F),(0x0370,0x03FF),(0x1E00,0x1EFF),(0x1F00,0x1FFF),(0x2070,0x209F),(0x2150,0x218F),(0x2460,0x24FF),(0xFB00,0xFB06),(0xFF01,0xFF5E)]
manual = {'ß':'ss','ẞ':'ss','æ':'ae','Æ':'ae','ø':'o','Ø':'o','œ':'oe','Œ':'oe','ł':'l','Ł':'l','đ':'d','Đ':'d','þ':'th','Þ':'th','ð':'d','Ð':'d','ı':'i','ħ':'h','Ħ':'h','ŧ':'t','Ŧ':'t','ŀ':'l','Ŀ':'l','ŉ':'n'}
out = {}
for lo,hi in ranges:
    for cp in range(lo,hi+1):
        c = chr(cp)
        if unicodedata.category(c).startswith('M'): continue
        if c in manual:
            r = manual[c]
        else:
            d = unicodedata.normalize('NFKD', c)
            d = ''.join(x for x in d if not unicodedata.category(x).startswith('M'))
            r = d.lower()
        if r == c.lower() or r == '':
            continue
        out[cp] = r
print("// Generated by scripts/gen-search-fold-table.py from Python's unicodedata (Unicode %s): each character's NFKD" % unicodedata.unidata_version)
print("// decomposition without combining marks, lowercased, for the characters where that differs")
print("// from the plain lowercase, plus letters that do not decompose (ß, æ, ø, œ, ł, đ, þ, ð, ı).")
print("// Sorted by character for a binary search.")
print("pub(super) static FOLD: &[(char, &str)] = &[")
for cp in sorted(out):
    r = out[cp].replace('\\','\\\\').replace('"','\\"')
    print('    (\'\\u{%04X}\', "%s"),' % (cp, ''.join(ch if 32 <= ord(ch) < 127 else '\\u{%04X}' % ord(ch) for ch in r)))
print("];")
