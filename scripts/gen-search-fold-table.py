#!/usr/bin/env python3
"""Write the fold table of the ontology entity search to stdout:

    python3 scripts/gen-search-fold-table.py > crates/sparkles/src/handles/ontology/search/fold_table.rs
    cargo fmt -p sparkles

Every character of Unicode is folded to its NFKD decomposition without the marks of the
combining diacritical mark blocks, recomposed with NFC and lowercased. NFC keeps Hangul
syllables and kana with voicing marks as they are, since their decompositions are not
diacritics. A few letters that do not decompose are folded by hand.
"""
import unicodedata

# the blocks whose marks folding drops, as `combining` in search/text.rs drops them
DIACRITICS = [(0x0300, 0x036F), (0x1AB0, 0x1AFF), (0x1DC0, 0x1DFF), (0x20D0, 0x20FF), (0xFE20, 0xFE2F)]
MANUAL = {'ß': 'ss', 'ẞ': 'ss', 'æ': 'ae', 'Æ': 'ae', 'ø': 'o', 'Ø': 'o', 'œ': 'oe', 'Œ': 'oe',
          'ł': 'l', 'Ł': 'l', 'đ': 'd', 'Đ': 'd', 'þ': 'th', 'Þ': 'th', 'ð': 'd', 'Ð': 'd',
          'ı': 'i', 'ħ': 'h', 'Ħ': 'h', 'ŧ': 't', 'Ŧ': 't', 'ŀ': 'l', 'Ŀ': 'l', 'ŉ': 'n'}


def diacritic(c):
    return any(lo <= ord(c) <= hi for lo, hi in DIACRITICS)


def fold(c):
    if c in MANUAL:
        return MANUAL[c]
    d = unicodedata.normalize('NFKD', c)
    return unicodedata.normalize('NFC', ''.join(x for x in d if not diacritic(x))).lower()


out = {}
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    if unicodedata.category(c).startswith('M'):
        continue
    r = fold(c)
    if r == c.lower() or r == '':
        continue
    out[cp] = r
print("// Generated by scripts/gen-search-fold-table.py from Python's unicodedata (Unicode %s): each" % unicodedata.unidata_version)
print("// character's NFKD decomposition without the combining diacritical marks, recomposed with NFC")
print("// and lowercased, for the characters where that differs from the plain lowercase, plus")
print("// letters that do not decompose (ß, æ, ø, œ, ł, đ, þ, ð, ı). Sorted by character for a")
print("// binary search.")
print("pub(super) static FOLD: &[(char, &str)] = &[")
for cp in sorted(out):
    r = out[cp].replace('\\', '\\\\').replace('"', '\\"')
    print('    (\'\\u{%04X}\', "%s"),' % (cp, ''.join(ch if 32 <= ord(ch) < 127 else '\\u{%04X}' % ord(ch) for ch in r)))
print("];")
