//! DOSDP/Cellfie-style parameterized axiom pattern rules with `${col}` and `${col|filter}`
//! placeholder substitution across Manchester and Functional-style OWL 2 syntax.

use super::{Context, Emitter, Limits, RowDiagnostic, Severity, Table, resolve_iri};
use crate::model::*;
use std::collections::BTreeMap;

/// Syntax used by a parameterized axiom rule template.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum PatternSyntax {
    #[default]
    Manchester,
    Functional,
}

impl PatternSyntax {
    pub fn parse(s: &str) -> Option<Self> {
        match s.trim().to_ascii_lowercase().as_str() {
            "manchester" => Some(Self::Manchester),
            "functional" | "ofn" => Some(Self::Functional),
            _ => None,
        }
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Manchester => "manchester",
            Self::Functional => "functional",
        }
    }
}

/// Optional column-to-entity declaration mapping for pattern mode.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ColumnDeclaration {
    pub column: String,
    pub kind: EntityKind,
    /// Optional split delimiter for multi-valued declaration columns.
    pub split: Option<String>,
}

/// An axiom annotation attached to axioms emitted by a [`PatternRule`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RuleAnnotation {
    /// Annotation property IRI or prefixed name.
    pub property: String,
    /// Value template with `${col}` placeholders.
    pub value: String,
    /// Optional language tag (`@en`).
    pub lang: Option<String>,
    /// Optional datatype IRI or prefixed name (`xsd:string`).
    pub datatype: Option<String>,
    /// When true, resolve the expanded value as an IRI instead of a literal.
    pub iri: bool,
}

/// A single DOSDP/Cellfie-style parameterized axiom template rule.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PatternRule {
    /// Optional human-readable name for diagnostics.
    pub name: Option<String>,
    /// Axiom template containing `${column}` or `${column|filter}` placeholders.
    pub template: String,
    /// Syntax of `template` (Manchester or Functional).
    pub syntax: PatternSyntax,
    /// When true (the default), skip the rule on a row if any referenced column is empty.
    pub skip_if_empty: bool,
    /// Columns that must be non-empty on every row (produces an error diagnostic if empty).
    pub required_columns: Vec<String>,
    /// Per-column split delimiters for multi-valued cells (Cartesian expansion, bounded).
    pub split: BTreeMap<String, String>,
    /// Axiom annotations attached to each axiom generated by this rule.
    pub annotations: Vec<RuleAnnotation>,
}

impl PatternRule {
    pub fn manchester(template: impl Into<String>) -> Self {
        Self {
            name: None,
            template: template.into(),
            syntax: PatternSyntax::Manchester,
            skip_if_empty: true,
            required_columns: Vec::new(),
            split: BTreeMap::new(),
            annotations: Vec::new(),
        }
    }

    pub fn functional(template: impl Into<String>) -> Self {
        Self {
            name: None,
            template: template.into(),
            syntax: PatternSyntax::Functional,
            skip_if_empty: true,
            required_columns: Vec::new(),
            split: BTreeMap::new(),
            annotations: Vec::new(),
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Filter {
    Raw,
    Iri,
    Slug,
    Str,
    Lang(String),
    Typed(String),
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Segment {
    Literal(String),
    Placeholder { column: String, filter: Filter },
}

/// Parse a template string containing `${col}` or `${col|filter}` placeholders.
fn parse_template(input: &str) -> Result<Vec<Segment>, String> {
    let mut out = Vec::new();
    let mut lit = String::new();
    let mut chars = input.char_indices().peekable();

    while let Some((idx, c)) = chars.next() {
        if c == '$' && chars.peek().is_some_and(|&(_, next)| next == '{') {
            chars.next(); // consume '{'
            if !lit.is_empty() {
                out.push(Segment::Literal(std::mem::take(&mut lit)));
            }
            let start = idx + 2;
            let mut end = None;
            for (j, ch) in chars.by_ref() {
                if ch == '}' {
                    end = Some(j);
                    break;
                }
            }
            let Some(end) = end else {
                return Err(format!("unclosed placeholder starting at byte {idx}"));
            };
            let expr = input[start..end].trim();
            if expr.is_empty() {
                return Err(format!("empty placeholder '${{}}' at byte {idx}"));
            }
            let (col, filter) = parse_placeholder_expr(expr)?;
            out.push(Segment::Placeholder {
                column: col,
                filter,
            });
        } else {
            lit.push(c);
        }
    }
    if !lit.is_empty() {
        out.push(Segment::Literal(lit));
    }
    Ok(out)
}

fn parse_placeholder_expr(expr: &str) -> Result<(String, Filter), String> {
    let Some((col, raw_filter)) = expr.split_once('|') else {
        return Ok((expr.to_string(), Filter::Raw));
    };
    let col = col.trim();
    if col.is_empty() {
        return Err(format!("placeholder '{expr}' has an empty column name"));
    }
    let f = raw_filter.trim();
    let filter = if f.eq_ignore_ascii_case("iri") {
        Filter::Iri
    } else if f.eq_ignore_ascii_case("slug") {
        Filter::Slug
    } else if f.eq_ignore_ascii_case("str") || f.eq_ignore_ascii_case("string") {
        Filter::Str
    } else if let Some(inner) = strip_call(f, "lang") {
        if inner.is_empty() {
            return Err("lang(...) filter requires a language tag".to_string());
        }
        Filter::Lang(inner.to_string())
    } else if let Some(inner) = strip_call(f, "type") {
        if inner.is_empty() {
            return Err("type(...) filter requires a datatype IRI or CURIE".to_string());
        }
        Filter::Typed(inner.to_string())
    } else {
        return Err(format!("unknown placeholder filter '{f}'"));
    };
    Ok((col.to_string(), filter))
}

fn strip_call<'a>(s: &'a str, name: &str) -> Option<&'a str> {
    if s.len() > name.len() + 2
        && s[..name.len()].eq_ignore_ascii_case(name)
        && s.as_bytes()[name.len()] == b'('
        && s.ends_with(')')
    {
        Some(s[name.len() + 1..s.len() - 1].trim())
    } else {
        None
    }
}

/// Evaluate DOSDP/Cellfie-style parameterized rules over `table`.
pub(crate) fn evaluate_rules(
    table: &Table,
    rules: &[PatternRule],
    declarations: &[ColumnDeclaration],
    ctx: &mut Context,
    limits: &Limits,
    emitter: &mut Emitter,
) {
    if table.rows.len() > limits.max_rows {
        emitter.diag(RowDiagnostic {
            row: table.rows[limits.max_rows].line,
            column: None,
            severity: Severity::Error,
            code: "too-many-rows".to_string(),
            message: format!(
                "table has {} data rows, exceeding the {} row limit",
                table.rows.len(),
                limits.max_rows
            ),
        });
        return;
    }

    if rules.is_empty() && declarations.is_empty() {
        emitter.diag(RowDiagnostic {
            row: 1,
            column: None,
            severity: Severity::Error,
            code: "empty-rules".to_string(),
            message: "pattern specification must define at least one rule or declaration"
                .to_string(),
        });
        return;
    }

    let header_idx: rustc_hash::FxHashMap<&str, usize> = table
        .headers
        .iter()
        .enumerate()
        .map(|(i, h)| (h.as_str(), i))
        .collect();

    // Parse all rule templates and validate column references upfront.
    struct CompiledRule<'a> {
        rule: &'a PatternRule,
        segments: Vec<Segment>,
        referenced: Vec<String>,
        annotations: Vec<(&'a RuleAnnotation, Vec<Segment>)>,
    }

    let mut compiled = Vec::with_capacity(rules.len());
    for (r_idx, rule) in rules.iter().enumerate() {
        let label = rule
            .name
            .clone()
            .unwrap_or_else(|| format!("rule_{}", r_idx + 1));
        let segments = match parse_template(&rule.template) {
            Ok(segs) => segs,
            Err(msg) => {
                emitter.diag(RowDiagnostic {
                    row: 1,
                    column: Some(label),
                    severity: Severity::Error,
                    code: "invalid-template".to_string(),
                    message: msg,
                });
                continue;
            }
        };
        let mut referenced = Vec::new();
        let mut missing_col = false;
        for seg in &segments {
            if let Segment::Placeholder { column, .. } = seg {
                if !header_idx.contains_key(column.as_str()) {
                    missing_col = true;
                    emitter.diag(RowDiagnostic {
                        row: 1,
                        column: Some(column.clone()),
                        severity: Severity::Error,
                        code: "unknown-column".to_string(),
                        message: format!(
                            "rule '{label}' references column '{column}', which is not in the table header"
                        ),
                    });
                } else if !referenced.contains(column) {
                    referenced.push(column.clone());
                }
            }
        }
        for req in &rule.required_columns {
            if !header_idx.contains_key(req.as_str()) {
                missing_col = true;
                emitter.diag(RowDiagnostic {
                    row: 1,
                    column: Some(req.clone()),
                    severity: Severity::Error,
                    code: "unknown-column".to_string(),
                    message: format!(
                        "rule '{label}' requires column '{req}', which is not in the table header"
                    ),
                });
            }
        }
        let mut compiled_anns = Vec::with_capacity(rule.annotations.len());
        for ann in &rule.annotations {
            match parse_template(&ann.value) {
                Ok(ann_segs) => {
                    for seg in &ann_segs {
                        if let Segment::Placeholder { column, .. } = seg
                            && !header_idx.contains_key(column.as_str())
                        {
                            missing_col = true;
                            emitter.diag(RowDiagnostic {
                                row: 1,
                                column: Some(column.clone()),
                                severity: Severity::Error,
                                code: "unknown-column".to_string(),
                                message: format!(
                                    "annotation template in rule '{label}' references unknown column '{column}'"
                                ),
                            });
                        }
                    }
                    compiled_anns.push((ann, ann_segs));
                }
                Err(msg) => {
                    missing_col = true;
                    emitter.diag(RowDiagnostic {
                        row: 1,
                        column: Some(label.clone()),
                        severity: Severity::Error,
                        code: "invalid-template".to_string(),
                        message: msg,
                    });
                }
            }
        }
        if !missing_col {
            compiled.push(CompiledRule {
                rule,
                segments,
                referenced,
                annotations: compiled_anns,
            });
        }
    }

    // Validate declaration columns.
    let mut resolved_decls: Vec<(usize, &ColumnDeclaration)> = Vec::new();
    for decl in declarations {
        if let Some(&idx) = header_idx.get(decl.column.as_str()) {
            resolved_decls.push((idx, decl));
        } else {
            emitter.diag(RowDiagnostic {
                row: 1,
                column: Some(decl.column.clone()),
                severity: Severity::Error,
                code: "unknown-column".to_string(),
                message: format!(
                    "declaration column '{}' is not in the table header",
                    decl.column
                ),
            });
        }
    }

    // Pass 1: register declared entities across all rows so Manchester rules can reference
    // entities introduced by the spreadsheet itself.
    for row in &table.rows {
        for &(col_idx, decl) in &resolved_decls {
            let cell = row.cells.get(col_idx).map(|s| s.trim()).unwrap_or("");
            if cell.is_empty() {
                continue;
            }
            for item in split_values(cell, decl.split.as_deref()) {
                if let Ok(iri) = resolve_iri(item, ctx) {
                    ctx.register_entity(&iri, decl.kind);
                }
            }
        }
    }

    // Pass 2: emit declaration axioms and rule axioms per row.
    for row in &table.rows {
        if row.cells.iter().all(|c| c.trim().is_empty()) {
            emitter.rows_skipped += 1;
            continue;
        }
        emitter.rows_processed += 1;

        for &(col_idx, decl) in &resolved_decls {
            let cell = row.cells.get(col_idx).map(|s| s.trim()).unwrap_or("");
            if cell.is_empty() {
                continue;
            }
            for item in split_values(cell, decl.split.as_deref()) {
                match resolve_iri(item, ctx) {
                    Ok(iri) => {
                        let entity = make_entity(iri, decl.kind);
                        emitter.declare(entity.clone());
                        if !emitter.emit(
                            Axiom::declaration(entity),
                            row.line,
                            Some(decl.column.clone()),
                        ) {
                            return;
                        }
                    }
                    Err(msg) => {
                        emitter.mark_row_error(row.line);
                        emitter.diag(RowDiagnostic {
                            row: row.line,
                            column: Some(decl.column.clone()),
                            severity: Severity::Error,
                            code: "invalid-iri".to_string(),
                            message: msg,
                        });
                    }
                }
            }
        }

        for cr in &compiled {
            // Check explicitly required columns first.
            let mut missing_req = false;
            for req in &cr.rule.required_columns {
                let idx = header_idx[req.as_str()];
                let val = row.cells.get(idx).map(|s| s.trim()).unwrap_or("");
                if val.is_empty() {
                    missing_req = true;
                    emitter.mark_row_error(row.line);
                    emitter.diag(RowDiagnostic {
                        row: row.line,
                        column: Some(req.clone()),
                        severity: Severity::Error,
                        code: "missing-required-column".to_string(),
                        message: format!("required column '{req}' is empty"),
                    });
                }
            }
            if missing_req {
                continue;
            }

            // Collect per-column value lists (applying configured split delimiters).
            let mut col_lists: Vec<(&str, Vec<&str>)> = Vec::with_capacity(cr.referenced.len());
            let mut skip = false;
            for col_name in &cr.referenced {
                let idx = header_idx[col_name.as_str()];
                let raw = row.cells.get(idx).map(|s| s.trim()).unwrap_or("");
                let vals = split_values(raw, cr.rule.split.get(col_name).map(String::as_str));
                if vals.is_empty() {
                    if cr.rule.skip_if_empty {
                        skip = true;
                        break;
                    } else {
                        emitter.mark_row_error(row.line);
                        emitter.diag(RowDiagnostic {
                            row: row.line,
                            column: Some(col_name.clone()),
                            severity: Severity::Error,
                            code: "empty-placeholder".to_string(),
                            message: format!("column '{col_name}' is empty"),
                        });
                        skip = true;
                        break;
                    }
                }
                col_lists.push((col_name.as_str(), vals));
            }
            if skip {
                continue;
            }

            // Check Cartesian expansion bound before expanding.
            let total_combos = col_lists
                .iter()
                .try_fold(1usize, |acc, (_, v)| acc.checked_mul(v.len()));
            if total_combos.is_none_or(|n| n > limits.max_rule_expansion_per_row) {
                emitter.mark_row_error(row.line);
                emitter.diag(RowDiagnostic {
                    row: row.line,
                    column: cr.rule.name.clone(),
                    severity: Severity::Error,
                    code: "expansion-limit".to_string(),
                    message: format!(
                        "multi-valued split expansion on this row exceeds the limit of {} axioms per rule",
                        limits.max_rule_expansion_per_row
                    ),
                });
                continue;
            }

            // Build binding combinations.
            let mut combos: Vec<rustc_hash::FxHashMap<&str, &str>> =
                vec![rustc_hash::FxHashMap::default()];
            for (col_name, vals) in &col_lists {
                let mut next = Vec::with_capacity(combos.len() * vals.len());
                for existing in &combos {
                    for &v in vals {
                        let mut cloned = existing.clone();
                        cloned.insert(*col_name, v);
                        next.push(cloned);
                    }
                }
                combos = next;
            }

            for bindings in &combos {
                let expanded = match render_segments(&cr.segments, bindings, row, &header_idx, ctx)
                {
                    Ok(s) => s,
                    Err(msg) => {
                        emitter.mark_row_error(row.line);
                        emitter.diag(RowDiagnostic {
                            row: row.line,
                            column: cr.rule.name.clone(),
                            severity: Severity::Error,
                            code: "template-substitution".to_string(),
                            message: msg,
                        });
                        continue;
                    }
                };

                let parsed_axiom = match cr.rule.syntax {
                    PatternSyntax::Manchester => {
                        crate::manchester::axiom(&expanded, &ctx.vocab).map_err(|e| e.message)
                    }
                    PatternSyntax::Functional => {
                        crate::ofn_read::parse_axiom(&expanded, ctx.vocab.prefixes())
                            .map_err(|e| e.message)
                    }
                };

                let mut ax = match parsed_axiom {
                    Ok(a) => a,
                    Err(msg) => {
                        emitter.mark_row_error(row.line);
                        emitter.diag(RowDiagnostic {
                            row: row.line,
                            column: cr.rule.name.clone(),
                            severity: Severity::Error,
                            code: "invalid-axiom-syntax".to_string(),
                            message: format!("{msg} (in '{expanded}')"),
                        });
                        continue;
                    }
                };

                // Attach optional rule annotations.
                for (ann_spec, ann_segs) in &cr.annotations {
                    let mut all_present = true;
                    for seg in ann_segs {
                        if let Segment::Placeholder { column, .. } = seg {
                            let val = bindings
                                .get(column.as_str())
                                .copied()
                                .or_else(|| {
                                    header_idx
                                        .get(column.as_str())
                                        .and_then(|&i| row.cells.get(i))
                                        .map(|s| s.trim())
                                })
                                .unwrap_or("");
                            if val.is_empty() {
                                all_present = false;
                                break;
                            }
                        }
                    }
                    if !all_present {
                        continue;
                    }
                    let prop_iri = match resolve_iri(&ann_spec.property, ctx) {
                        Ok(i) => i,
                        Err(msg) => {
                            emitter.mark_row_error(row.line);
                            emitter.diag(RowDiagnostic {
                                row: row.line,
                                column: cr.rule.name.clone(),
                                severity: Severity::Error,
                                code: "invalid-iri".to_string(),
                                message: msg,
                            });
                            continue;
                        }
                    };
                    let val_str = match render_segments(ann_segs, bindings, row, &header_idx, ctx) {
                        Ok(s) => s,
                        Err(msg) => {
                            emitter.mark_row_error(row.line);
                            emitter.diag(RowDiagnostic {
                                row: row.line,
                                column: cr.rule.name.clone(),
                                severity: Severity::Error,
                                code: "template-substitution".to_string(),
                                message: msg,
                            });
                            continue;
                        }
                    };
                    let ann_val = if ann_spec.iri {
                        match resolve_iri(&val_str, ctx) {
                            Ok(iri) => AnnotationValue::Iri(iri),
                            Err(msg) => {
                                emitter.mark_row_error(row.line);
                                emitter.diag(RowDiagnostic {
                                    row: row.line,
                                    column: cr.rule.name.clone(),
                                    severity: Severity::Error,
                                    code: "invalid-iri".to_string(),
                                    message: msg,
                                });
                                continue;
                            }
                        }
                    } else if let Some(lang) = &ann_spec.lang {
                        match Literal::lang(val_str, lang) {
                            Ok(lit) => AnnotationValue::Literal(lit),
                            Err(e) => {
                                emitter.mark_row_error(row.line);
                                emitter.diag(RowDiagnostic {
                                    row: row.line,
                                    column: cr.rule.name.clone(),
                                    severity: Severity::Error,
                                    code: "invalid-language-tag".to_string(),
                                    message: e.0,
                                });
                                continue;
                            }
                        }
                    } else if let Some(dt) = &ann_spec.datatype {
                        match resolve_iri(dt, ctx) {
                            Ok(dt_iri) => {
                                AnnotationValue::Literal(Literal::typed(val_str, dt_iri.as_str()))
                            }
                            Err(msg) => {
                                emitter.mark_row_error(row.line);
                                emitter.diag(RowDiagnostic {
                                    row: row.line,
                                    column: cr.rule.name.clone(),
                                    severity: Severity::Error,
                                    code: "invalid-iri".to_string(),
                                    message: msg,
                                });
                                continue;
                            }
                        }
                    } else {
                        AnnotationValue::Literal(Literal::simple(val_str))
                    };
                    ax.annotations.insert(Annotation {
                        property: AnnotationProperty(prop_iri),
                        value: ann_val,
                        annotations: Default::default(),
                    });
                }

                if !emitter.emit(ax, row.line, cr.rule.name.clone()) {
                    return;
                }
            }
        }
    }
}

fn split_values<'a>(cell: &'a str, sep: Option<&str>) -> Vec<&'a str> {
    if cell.is_empty() {
        return Vec::new();
    }
    match sep {
        Some(s) if !s.is_empty() => cell
            .split(s)
            .map(str::trim)
            .filter(|v| !v.is_empty())
            .collect(),
        _ => vec![cell],
    }
}

fn render_segments(
    segments: &[Segment],
    bindings: &rustc_hash::FxHashMap<&str, &str>,
    row: &super::TableRow,
    header_idx: &rustc_hash::FxHashMap<&str, usize>,
    ctx: &Context,
) -> Result<String, String> {
    let mut out = String::new();
    for seg in segments {
        match seg {
            Segment::Literal(s) => out.push_str(s),
            Segment::Placeholder { column, filter } => {
                let raw = bindings
                    .get(column.as_str())
                    .copied()
                    .or_else(|| {
                        header_idx
                            .get(column.as_str())
                            .and_then(|&i| row.cells.get(i))
                            .map(|s| s.trim())
                    })
                    .unwrap_or("");
                match filter {
                    Filter::Raw => out.push_str(raw),
                    Filter::Iri => {
                        let iri = resolve_iri(raw, ctx)?;
                        out.push('<');
                        out.push_str(iri.as_str());
                        out.push('>');
                    }
                    Filter::Slug => {
                        out.push_str(&slugify(raw));
                    }
                    Filter::Str => {
                        out.push('"');
                        escape_string(raw, &mut out);
                        out.push('"');
                    }
                    Filter::Lang(tag) => {
                        out.push('"');
                        escape_string(raw, &mut out);
                        out.push_str("\"@");
                        out.push_str(tag);
                    }
                    Filter::Typed(dt) => {
                        let dt_iri = resolve_iri(dt, ctx)?;
                        out.push('"');
                        escape_string(raw, &mut out);
                        out.push_str("\"^^<");
                        out.push_str(dt_iri.as_str());
                        out.push('>');
                    }
                }
            }
        }
    }
    Ok(out)
}

fn escape_string(s: &str, out: &mut String) {
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
}

fn slugify(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut prev_sep = false;
    for c in s.trim().chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
            prev_sep = false;
        } else if (c.is_whitespace() || c == '-' || c == '_' || c == '/')
            && !prev_sep
            && !out.is_empty()
        {
            out.push('_');
            prev_sep = true;
        }
    }
    while out.ends_with('_') {
        out.pop();
    }
    out
}

fn make_entity(iri: Iri, kind: EntityKind) -> Entity {
    match kind {
        EntityKind::Class => Entity::Class(Class(iri)),
        EntityKind::Datatype => Entity::Datatype(Datatype(iri)),
        EntityKind::ObjectProperty => Entity::ObjectProperty(ObjectProperty(iri)),
        EntityKind::DataProperty => Entity::DataProperty(DataProperty(iri)),
        EntityKind::AnnotationProperty => Entity::AnnotationProperty(AnnotationProperty(iri)),
        EntityKind::NamedIndividual => Entity::NamedIndividual(NamedIndividual(iri)),
    }
}
