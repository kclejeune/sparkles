use std::collections::BTreeMap;

/// Syntax used by a parameterized axiom rule template.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum PatternSyntax {
    #[default]
    Manchester,
    Functional,
}

impl PatternSyntax {
    pub fn parse(s: &str) -> Option<Self> {
        match s.trim().to_ascii_lowercase().as_str() {
            "manchester" => Some(Self::Manchester),
            "functional" | "ofn" => Some(Self::Functional),
            _ => None,
        }
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Manchester => "manchester",
            Self::Functional => "functional",
        }
    }
}

/// Optional column-to-entity declaration mapping for pattern mode.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ColumnDeclaration {
    pub column: String,
    pub kind: EntityKind,
    /// Optional split delimiter for multi-valued declaration columns.
    pub split: Option<String>,
}

/// An axiom annotation attached to axioms emitted by a [`PatternRule`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RuleAnnotation {
    /// Annotation property IRI or prefixed name.
    pub property: String,
    /// Value template with `${col}` placeholders.
    pub value: String,
    /// Optional language tag (`@en`).
    pub lang: Option<String>,
    /// Optional datatype IRI or prefixed name (`xsd:string`).
    pub datatype: Option<String>,
    /// When true, resolve the expanded value as an IRI instead of a literal.
    pub iri: bool,
}

/// A single DOSDP/Cellfie-style parameterized axiom template rule.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PatternRule {
    /// Optional human-readable name for diagnostics.
    pub name: Option<String>,
    /// Axiom template containing `${column}` or `${column|filter}` placeholders.
    pub template: String,
    /// Syntax of `template` (Manchester or Functional).
    pub syntax: PatternSyntax,
    /// When true (the default), skip the rule on a row if any referenced column is empty.
    pub skip_if_empty: bool,
    /// Columns that must be non-empty on every row (produces an error diagnostic if empty).
    pub required_columns: Vec<String>,
    /// Per-column split delimiters for multi-valued cells (Cartesian expansion, bounded).
    pub split: BTreeMap<String, String>,
    /// Axiom annotations attached to each axiom generated by this rule.
    pub annotations: Vec<RuleAnnotation>,
}

impl PatternRule {
    pub fn manchester(template: impl Into<String>) -> Self {
        Self {
            name: None,
            template: template.into(),
            syntax: PatternSyntax::Manchester,
            skip_if_empty: true,
            required_columns: Vec::new(),
            split: BTreeMap::new(),
            annotations: Vec::new(),
        }
    }

    pub fn functional(template: impl Into<String>) -> Self {
        Self {
            name: None,
            template: template.into(),
            syntax: PatternSyntax::Functional,
            skip_if_empty: true,
            required_columns: Vec::new(),
            split: BTreeMap::new(),
            annotations: Vec::new(),
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Filter {
    Raw,
    Iri,
    Slug,
    Str,
    Lang(String),
    Typed(String),
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Segment {
    Literal(String),
    Placeholder { column: String, filter: Filter },
}

/// Parse a template string containing `${col}` or `${col|filter}` placeholders.
fn parse_template(input: &str) -> Result<Vec<Segment>, String> {
    let mut out = Vec::new();
    let mut lit = String::new();
    let mut chars = input.char_indices().peekable();

    while let Some((idx, c)) = chars.next() {
        if c == '$' && chars.peek().is_some_and(|&(_, next)| next == '{') {
            chars.next(); // consume '{'
            if !lit.is_empty() {
                out.push(Segment::Literal(std::mem::take(&mut lit)));
            }
            let start = idx + 2;
            let mut end = None;
            for (j, ch) in chars.by_ref() {
                if ch == '}' {
                    end = Some(j);
                    break;
                }
            }
            let Some(end) = end else {
                return Err(format!("unclosed placeholder starting at byte {idx}"));
            };
            let expr = input[start..end].trim();
            if expr.is_empty() {
                return Err(format!("empty placeholder '${{}}' at byte {idx}"));
            }
            let (col, filter) = parse_placeholder_expr(expr)?;
            out.push(Segment::Placeholder {
                column: col,
                filter,
            });
        } else {
            lit.push(c);
        }
    }
    if !lit.is_empty() {
        out.push(Segment::Literal(lit));
    }
    Ok(out)
}

fn parse_placeholder_expr(expr: &str) -> Result<(String, Filter), String> {
    let Some((col, raw_filter)) = expr.split_once('|') else {
        return Ok((expr.to_string(), Filter::Raw));
    };
    let col = col.trim();
    if col.is_empty() {
        return Err(format!("placeholder '{expr}' has an empty column name"));
    }
    let f = raw_filter.trim();
    let filter = if f.eq_ignore_ascii_case("iri") {
        Filter::Iri
    } else if f.eq_ignore_ascii_case("slug") {
        Filter::Slug
    } else if f.eq_ignore_ascii_case("str") || f.eq_ignore_ascii_case("string") {
        Filter::Str
    } else if let Some(inner) = strip_call(f, "lang") {
        if inner.is_empty() {
            return Err("lang(...) filter requires a language tag".to_string());
        }
        Filter::Lang(inner.to_string())
    } else if let Some(inner) = strip_call(f, "type") {
        if inner.is_empty() {
            return Err("type(...) filter requires a datatype IRI or CURIE".to_string());
        }
        Filter::Typed(inner.to_string())
    } else {
        return Err(format!("unknown placeholder filter '{f}'"));
    };
    Ok((col.to_string(), filter))
}

/// Safely match an ASCII `name(...)` call without risking mid-UTF-8-char slices.
fn strip_call<'a>(s: &'a str, name: &str) -> Option<&'a str> {
    debug_assert!(name.is_ascii());
    let bytes = s.as_bytes();
    if bytes.len() >= name.len() + 2
        && bytes[..name.len()].eq_ignore_ascii_case(name.as_bytes())
        && bytes[name.len()] == b'('
        && bytes[bytes.len() - 1] == b')'
    {
        Some(s[name.len() + 1..s.len() - 1].trim())
    } else {
        None
    }
}

/// Evaluate DOSDP/Cellfie-style parameterized rules over `table`.
#[allow(clippy::too_many_arguments)]
pub(crate) fn evaluate_rules(
    table: &Table,
    rules: &[PatternRule],
    declarations: &[ColumnDeclaration],
    base_vocab: &Vocabulary,
    spec: &PatternSpec,
    limits: &Limits,
    initial_diagnostics: &[RowDiagnostic],
    initial_truncated: bool,
    emitter: &mut Emitter,
    check_cancel: &mut dyn FnMut() -> Result<(), CancelReason>,
) -> Result<(), EvalError> {
    if table.rows.len() > limits.max_rows {
        emitter.structural_error(RowDiagnostic {
            row: table.rows[limits.max_rows].line,
            column: None,
            severity: Severity::Error,
            code: "too-many-rows".to_string(),
            message: format!(
                "table has {} data rows, exceeding the {} row limit",
                table.rows.len(),
                limits.max_rows
            ),
        });
        return Ok(());
    }

    if rules.is_empty() && declarations.is_empty() {
        emitter.structural_error(RowDiagnostic {
            row: 1,
            column: None,
            severity: Severity::Error,
            code: "empty-rules".to_string(),
            message: "pattern specification must define at least one rule or declaration"
                .to_string(),
        });
        return Ok(());
    }

    // Track first index and occurrence counts so duplicate column references are diagnosed
    // consistently rather than silently picking first vs last.
    let mut header_idx: FxHashMap<&str, usize> = FxHashMap::default();
    let mut header_counts: FxHashMap<&str, usize> = FxHashMap::default();
    for (i, h) in table.headers.iter().enumerate() {
        *header_counts.entry(h.as_str()).or_insert(0) += 1;
        header_idx.entry(h.as_str()).or_insert(i);
    }

    let mut structural_diags = StructuralDiags::new(limits);
    let check_column = |col: &str, context: &str, out: &mut StructuralDiags| -> bool {
        match header_counts.get(col).copied().unwrap_or(0) {
            0 => {
                let col_snip = bounded_col(col);
                out.push(1, Some(&col_snip), "unknown-column", || {
                    format!(
                        "{context} references column '{col_snip}', which is not in the table header"
                    )
                });
                false
            }
            1 => true,
            _ => {
                let col_snip = bounded_col(col);
                out.push(1, Some(&col_snip), "ambiguous-column", || {
                    format!("{context} references duplicate column header '{col_snip}'")
                });
                false
            }
        }
    };

    struct CompiledAnn<'a> {
        spec: &'a RuleAnnotation,
        segments: Vec<Segment>,
        /// Annotation-only placeholder columns (not bound by the rule template).
        extra_cols: Vec<(String, String)>,
    }

    struct CompiledRule<'a> {
        rule: &'a PatternRule,
        diag_name: Option<String>,
        segments: Vec<Segment>,
        referenced: Vec<(String, String)>,
        required_cols: Vec<(String, String)>,
        annotations: Vec<CompiledAnn<'a>>,
    }

    let mut compiled = Vec::with_capacity(rules.len());
    for (r_idx, rule) in rules.iter().enumerate() {
        let diag_name = rule.name.as_deref().map(bounded_col);
        let label = diag_name
            .clone()
            .unwrap_or_else(|| format!("rule_{}", r_idx + 1));
        let segments = match parse_template(&rule.template) {
            Ok(segs) => segs,
            Err(msg) => {
                structural_diags.push(1, Some(&label), "invalid-template", || msg);
                continue;
            }
        };
        let mut referenced: Vec<(String, String)> = Vec::new();
        let mut rule_invalid = false;
        let rule_ctx = format!("rule '{label}'");
        for seg in &segments {
            if let Segment::Placeholder { column, .. } = seg {
                if !check_column(column, &rule_ctx, &mut structural_diags) {
                    rule_invalid = true;
                } else if !referenced.iter().any(|(c, _)| c == column) {
                    referenced.push((column.clone(), bounded_col(column)));
                }
            }
        }
        let req_ctx = format!("rule '{label}' requiredColumns");
        let mut required_cols: Vec<(String, String)> =
            Vec::with_capacity(rule.required_columns.len());
        for req in &rule.required_columns {
            if !check_column(req, &req_ctx, &mut structural_diags) {
                rule_invalid = true;
            } else {
                required_cols.push((req.clone(), bounded_col(req)));
            }
        }
        let split_ctx = format!("rule '{label}' split");
        for split_col in rule.split.keys() {
            if !check_column(split_col, &split_ctx, &mut structural_diags) {
                rule_invalid = true;
            }
        }
        let ann_ctx = format!("annotation template in rule '{label}'");
        let mut compiled_anns = Vec::with_capacity(rule.annotations.len());
        for ann in &rule.annotations {
            if ann.iri && (ann.lang.is_some() || ann.datatype.is_some()) {
                rule_invalid = true;
                structural_diags.push(1, Some(&label), "invalid-annotation", || {
                    format!(
                        "annotation in rule '{label}' cannot combine iri=true with lang or datatype"
                    )
                });
                continue;
            }
            if ann.lang.is_some() && ann.datatype.is_some() {
                rule_invalid = true;
                structural_diags.push(1, Some(&label), "invalid-annotation", || {
                    format!("annotation in rule '{label}' cannot specify both lang and datatype")
                });
                continue;
            }
            match parse_template(&ann.value) {
                Ok(ann_segs) => {
                    let mut extra_cols: Vec<(String, String)> = Vec::new();
                    for seg in &ann_segs {
                        if let Segment::Placeholder { column, .. } = seg {
                            if !check_column(column, &ann_ctx, &mut structural_diags) {
                                rule_invalid = true;
                            } else if !referenced.iter().any(|(c, _)| c == column)
                                && !extra_cols.iter().any(|(c, _)| c == column)
                            {
                                extra_cols.push((column.clone(), bounded_col(column)));
                            }
                        }
                    }
                    compiled_anns.push(CompiledAnn {
                        spec: ann,
                        segments: ann_segs,
                        extra_cols,
                    });
                }
                Err(msg) => {
                    rule_invalid = true;
                    structural_diags.push(1, Some(&label), "invalid-template", || msg);
                }
            }
        }
        if !rule_invalid {
            compiled.push(CompiledRule {
                rule,
                diag_name,
                segments,
                referenced,
                required_cols,
                annotations: compiled_anns,
            });
        }
    }

    // Validate declaration columns.
    let mut resolved_decls: Vec<(usize, &ColumnDeclaration, String)> = Vec::new();
    for decl in declarations {
        if check_column(&decl.column, "declaration", &mut structural_diags) {
            resolved_decls.push((
                header_idx[decl.column.as_str()],
                decl,
                bounded_col(&decl.column),
            ));
        }
    }

    let n = table.rows.len();
    let mut convergence = VocabConvergence::new(n);

    for round in 0..MAX_VOCAB_ROUNDS {
        if round > 0 {
            emitter.reset_for_retry(initial_diagnostics, initial_truncated);
        }
        structural_diags.replay_into(emitter);

        let mut ctx = Context::build(base_vocab, spec);
        let mut round_contributed = vec![false; n];
        let mut round_failed = vec![false; n];
        let mut row_pass1_ok = vec![true; n];

        // Pass 1: register declared entities ONLY for eligible rows whose declarations are
        // all valid and non-truncated so failed/truncated rows never enter the vocabulary.
        for (row_i, row) in table.rows.iter().enumerate() {
            if row_i.is_multiple_of(64) {
                check_cancel()?;
            }
            if !convergence.vocab_eligible[row_i] {
                continue;
            }
            let mut staged_decls: Vec<(Iri, EntityKind)> = Vec::new();
            let mut decls_ok = true;
            for &(col_idx, decl, ref diag_col) in &resolved_decls {
                let cell = row.cells.get(col_idx).map(|s| s.trim()).unwrap_or("");
                if cell.is_empty() {
                    continue;
                }
                let (items, truncated) = split_values_bounded(
                    cell,
                    decl.split.as_deref(),
                    limits.max_split_values_per_cell,
                );
                if truncated {
                    decls_ok = false;
                    break;
                }
                for item in items {
                    match resolve_iri_charged(
                        item,
                        &ctx,
                        emitter,
                        row.line,
                        Some(diag_col.as_str()),
                    ) {
                        Ok(iri) => staged_decls.push((iri, decl.kind)),
                        Err(ResolveError::Budget) => return Ok(()),
                        Err(ResolveError::Invalid(_)) => {
                            decls_ok = false;
                            break;
                        }
                    }
                }
                if !decls_ok {
                    break;
                }
            }
            if !decls_ok {
                row_pass1_ok[row_i] = false;
                continue;
            }
            for (iri, kind) in staged_decls {
                let vocab_bytes = iri.as_str().len().saturating_mul(2);
                if !emitter.charge_vocab_bytes(row.line, vocab_bytes) {
                    return Ok(());
                }
                ctx.register_entity(&iri, kind);
                round_contributed[row_i] = true;
            }
        }

        // Pass 2: stage and emit declaration axioms and rule axioms per row.
        for (row_i, row) in table.rows.iter().enumerate() {
            check_cancel()?;
            if row.cells.iter().all(|c| c.trim().is_empty()) {
                emitter.rows_skipped += 1;
                continue;
            }
            emitter.rows_processed += 1;

            let mut row_has_error = false;
            let mut row_declarations: Vec<Entity> = Vec::new();
            let mut row_axioms: Vec<(Axiom, Option<&str>)> = Vec::new();

            for &(col_idx, decl, ref diag_col) in &resolved_decls {
                let cell = row.cells.get(col_idx).map(|s| s.trim()).unwrap_or("");
                if cell.is_empty() {
                    continue;
                }
                let (items, truncated) = split_values_bounded(
                    cell,
                    decl.split.as_deref(),
                    limits.max_split_values_per_cell,
                );
                if truncated {
                    row_has_error = true;
                    emitter.diag(RowDiagnostic {
                        row: row.line,
                        column: Some(diag_col.clone()),
                        severity: Severity::Error,
                        code: "expansion-limit".to_string(),
                        message: format!(
                            "declaration column '{diag_col}' split exceeds the limit of {} values",
                            limits.max_split_values_per_cell
                        ),
                    });
                    continue;
                }
                for item in items {
                    if !emitter.charge_attempt(1, row.line, Some(diag_col.as_str())) {
                        return Ok(());
                    }
                    match resolve_iri_charged(
                        item,
                        &ctx,
                        emitter,
                        row.line,
                        Some(diag_col.as_str()),
                    ) {
                        Ok(iri) => {
                            if !emitter.charge_expanded_bytes(
                                iri.as_str().len(),
                                row.line,
                                Some(diag_col.as_str()),
                            ) {
                                return Ok(());
                            }
                            let entity = make_entity(iri, decl.kind);
                            row_declarations.push(entity.clone());
                            row_axioms.push((Axiom::declaration(entity), Some(diag_col.as_str())));
                        }
                        Err(ResolveError::Budget) => return Ok(()),
                        Err(ResolveError::Invalid(msg)) => {
                            row_has_error = true;
                            emitter.diag(RowDiagnostic {
                                row: row.line,
                                column: Some(diag_col.clone()),
                                severity: Severity::Error,
                                code: "invalid-iri".to_string(),
                                message: msg,
                            });
                        }
                    }
                }
            }

            for cr in &compiled {
                let rule_col = cr.diag_name.as_deref();
                // Check explicitly required columns first.
                let mut missing_req = false;
                for (req, req_diag) in &cr.required_cols {
                    let idx = header_idx[req.as_str()];
                    let val = row.cells.get(idx).map(|s| s.trim()).unwrap_or("");
                    if val.is_empty() {
                        missing_req = true;
                        row_has_error = true;
                        emitter.diag(RowDiagnostic {
                            row: row.line,
                            column: Some(req_diag.clone()),
                            severity: Severity::Error,
                            code: "missing-required-column".to_string(),
                            message: format!("required column '{req_diag}' is empty"),
                        });
                    }
                }
                if missing_req {
                    continue;
                }

                // Collect per-column value lists (applying configured split delimiters).
                let mut col_lists: Vec<(&str, Vec<&str>)> = Vec::with_capacity(cr.referenced.len());
                let mut skip = false;
                for (col_name, col_diag) in &cr.referenced {
                    let idx = header_idx[col_name.as_str()];
                    let raw = row.cells.get(idx).map(|s| s.trim()).unwrap_or("");
                    let (vals, truncated) = split_values_bounded(
                        raw,
                        cr.rule.split.get(col_name).map(String::as_str),
                        limits.max_split_values_per_cell,
                    );
                    if truncated {
                        row_has_error = true;
                        emitter.diag(RowDiagnostic {
                            row: row.line,
                            column: Some(col_diag.clone()),
                            severity: Severity::Error,
                            code: "expansion-limit".to_string(),
                            message: format!(
                                "column '{col_diag}' split exceeds the limit of {} values",
                                limits.max_split_values_per_cell
                            ),
                        });
                        skip = true;
                        break;
                    }
                    if vals.is_empty() {
                        if cr.rule.skip_if_empty {
                            skip = true;
                            break;
                        } else {
                            row_has_error = true;
                            emitter.diag(RowDiagnostic {
                                row: row.line,
                                column: Some(col_diag.clone()),
                                severity: Severity::Error,
                                code: "empty-placeholder".to_string(),
                                message: format!("column '{col_diag}' is empty"),
                            });
                            skip = true;
                            break;
                        }
                    }
                    col_lists.push((col_name.as_str(), vals));
                }
                if skip {
                    continue;
                }

                // Check Cartesian expansion bound before expanding.
                let total_combos = col_lists
                    .iter()
                    .try_fold(1usize, |acc, (_, v)| acc.checked_mul(v.len()));
                if total_combos.is_none_or(|n| n > limits.max_rule_expansion_per_row) {
                    row_has_error = true;
                    emitter.diag(RowDiagnostic {
                        row: row.line,
                        column: cr.diag_name.clone(),
                        severity: Severity::Error,
                        code: "expansion-limit".to_string(),
                        message: format!(
                            "multi-valued split expansion on this row exceeds the limit of {} axioms per rule",
                            limits.max_rule_expansion_per_row
                        ),
                    });
                    continue;
                }

                // Build binding combinations.
                let mut combos: Vec<FxHashMap<&str, &str>> = vec![FxHashMap::default()];
                for (col_name, vals) in &col_lists {
                    let mut next = Vec::with_capacity(combos.len() * vals.len());
                    for existing in &combos {
                        for &v in vals {
                            let mut cloned = existing.clone();
                            cloned.insert(*col_name, v);
                            next.push(cloned);
                        }
                    }
                    combos = next;
                }

                for (combo_i, bindings) in combos.iter().enumerate() {
                    if combo_i.is_multiple_of(64) {
                        check_cancel()?;
                    }
                    if !emitter.charge_attempt(1, row.line, rule_col) {
                        return Ok(());
                    }

                    let expanded = match render_segments_bounded(
                        &cr.segments,
                        bindings,
                        row,
                        &header_idx,
                        &ctx,
                        cr.rule.syntax,
                        limits.max_expanded_bytes_per_template,
                        emitter,
                        row.line,
                        rule_col,
                    ) {
                        Ok(s) => s,
                        Err(RenderError::Budget) => return Ok(()),
                        Err(RenderError::Row(msg)) => {
                            row_has_error = true;
                            emitter.diag(RowDiagnostic {
                                row: row.line,
                                column: cr.diag_name.clone(),
                                severity: Severity::Error,
                                code: "template-substitution".to_string(),
                                message: msg,
                            });
                            continue;
                        }
                    };

                    let mut ax = match parse_axiom_charged(
                        &expanded,
                        cr.rule.syntax,
                        &ctx,
                        emitter,
                        row.line,
                        rule_col,
                    ) {
                        Ok(a) => a,
                        Err(ResolveError::Budget) => return Ok(()),
                        Err(ResolveError::Invalid(msg)) => {
                            row_has_error = true;
                            let code = if msg.contains("byte limit") {
                                "expansion-bytes-limit"
                            } else {
                                "invalid-axiom-syntax"
                            };
                            let message = if code == "expansion-bytes-limit" {
                                msg
                            } else {
                                format!("{msg} (in '{}')", truncated_snippet(&expanded, 256))
                            };
                            emitter.diag(RowDiagnostic {
                                row: row.line,
                                column: cr.diag_name.clone(),
                                severity: Severity::Error,
                                code: code.to_string(),
                                message,
                            });
                            continue;
                        }
                    };

                    // Enforce per-axiom annotation cap on inline OFN/Manchester annotations
                    // even when the rule defines no separate `annotations` entries.
                    if count_annotations(&ax.annotations) > limits.max_annotations_per_axiom {
                        row_has_error = true;
                        emitter.diag(RowDiagnostic {
                            row: row.line,
                            column: cr.diag_name.clone(),
                            severity: Severity::Error,
                            code: "annotation-limit".to_string(),
                            message: format!(
                                "axiom annotations exceed the limit of {} per axiom",
                                limits.max_annotations_per_axiom
                            ),
                        });
                        continue;
                    }

                    // Attach optional rule annotations (supporting bounded splits on
                    // annotation-only columns).
                    let mut ann_failed = false;
                    for ann in &cr.annotations {
                        let mut extra_lists: Vec<(&str, Vec<&str>)> =
                            Vec::with_capacity(ann.extra_cols.len());
                        let mut ann_skip = false;
                        // Check template-bound placeholders referenced by the annotation.
                        for seg in &ann.segments {
                            if let Segment::Placeholder { column, .. } = seg
                                && let Some(&v) = bindings.get(column.as_str())
                                && v.is_empty()
                            {
                                ann_skip = true;
                                break;
                            }
                        }
                        if ann_skip {
                            continue;
                        }
                        for (col_name, col_diag) in &ann.extra_cols {
                            let idx = header_idx[col_name.as_str()];
                            let raw = row.cells.get(idx).map(|s| s.trim()).unwrap_or("");
                            let (vals, truncated) = split_values_bounded(
                                raw,
                                cr.rule.split.get(col_name).map(String::as_str),
                                limits.max_split_values_per_cell,
                            );
                            if truncated {
                                ann_failed = true;
                                row_has_error = true;
                                emitter.diag(RowDiagnostic {
                                    row: row.line,
                                    column: Some(col_diag.clone()),
                                    severity: Severity::Error,
                                    code: "expansion-limit".to_string(),
                                    message: format!(
                                        "annotation column '{col_diag}' split exceeds the limit of {} values",
                                        limits.max_split_values_per_cell
                                    ),
                                });
                                ann_skip = true;
                                break;
                            }
                            if vals.is_empty() {
                                ann_skip = true;
                                break;
                            }
                            extra_lists.push((col_name.as_str(), vals));
                        }
                        if ann_skip {
                            continue;
                        }

                        let ann_combo_count = extra_lists
                            .iter()
                            .try_fold(1usize, |acc, (_, v)| acc.checked_mul(v.len()));
                        let existing_anns = count_annotations(&ax.annotations);
                        let Some(ann_combo_count) = ann_combo_count.filter(|&n| {
                            existing_anns.saturating_add(n) <= limits.max_annotations_per_axiom
                        }) else {
                            ann_failed = true;
                            row_has_error = true;
                            emitter.diag(RowDiagnostic {
                                row: row.line,
                                column: cr.diag_name.clone(),
                                severity: Severity::Error,
                                code: "annotation-limit".to_string(),
                                message: format!(
                                    "rule annotations exceed the limit of {} per axiom",
                                    limits.max_annotations_per_axiom
                                ),
                            });
                            continue;
                        };

                        if !emitter.charge_attempt(ann_combo_count, row.line, rule_col) {
                            return Ok(());
                        }

                        let prop_iri = match resolve_iri_charged(
                            &ann.spec.property,
                            &ctx,
                            emitter,
                            row.line,
                            rule_col,
                        ) {
                            Ok(i) => i,
                            Err(ResolveError::Budget) => return Ok(()),
                            Err(ResolveError::Invalid(msg)) => {
                                ann_failed = true;
                                row_has_error = true;
                                emitter.diag(RowDiagnostic {
                                    row: row.line,
                                    column: cr.diag_name.clone(),
                                    severity: Severity::Error,
                                    code: "invalid-iri".to_string(),
                                    message: msg,
                                });
                                continue;
                            }
                        };

                        if ann_combo_count > 1 {
                            let extra_prop_bytes =
                                prop_iri.as_str().len().saturating_mul(ann_combo_count - 1);
                            if !emitter.charge_expanded_bytes(extra_prop_bytes, row.line, rule_col)
                            {
                                return Ok(());
                            }
                        }

                        let mut ann_combos: Vec<FxHashMap<&str, &str>> = vec![bindings.clone()];
                        for (col_name, vals) in &extra_lists {
                            let mut next = Vec::with_capacity(ann_combos.len() * vals.len());
                            for existing in &ann_combos {
                                for &v in vals {
                                    let mut cloned = existing.clone();
                                    cloned.insert(*col_name, v);
                                    next.push(cloned);
                                }
                            }
                            ann_combos = next;
                        }

                        for ann_bindings in &ann_combos {
                            let val_str = match render_segments_bounded(
                                &ann.segments,
                                ann_bindings,
                                row,
                                &header_idx,
                                &ctx,
                                cr.rule.syntax,
                                limits.max_expanded_bytes_per_template,
                                emitter,
                                row.line,
                                rule_col,
                            ) {
                                Ok(s) => s,
                                Err(RenderError::Budget) => return Ok(()),
                                Err(RenderError::Row(msg)) => {
                                    ann_failed = true;
                                    row_has_error = true;
                                    emitter.diag(RowDiagnostic {
                                        row: row.line,
                                        column: cr.diag_name.clone(),
                                        severity: Severity::Error,
                                        code: "template-substitution".to_string(),
                                        message: msg,
                                    });
                                    continue;
                                }
                            };
                            let ann_val = if ann.spec.iri {
                                match resolve_iri_charged(
                                    &val_str, &ctx, emitter, row.line, rule_col,
                                ) {
                                    Ok(iri) => AnnotationValue::Iri(iri),
                                    Err(ResolveError::Budget) => return Ok(()),
                                    Err(ResolveError::Invalid(msg)) => {
                                        ann_failed = true;
                                        row_has_error = true;
                                        emitter.diag(RowDiagnostic {
                                            row: row.line,
                                            column: cr.diag_name.clone(),
                                            severity: Severity::Error,
                                            code: "invalid-iri".to_string(),
                                            message: msg,
                                        });
                                        continue;
                                    }
                                }
                            } else if let Some(lang) = &ann.spec.lang {
                                if !emitter.charge_expanded_bytes(lang.len(), row.line, rule_col) {
                                    return Ok(());
                                }
                                match Literal::lang(val_str, lang) {
                                    Ok(lit) => AnnotationValue::Literal(lit),
                                    Err(e) => {
                                        ann_failed = true;
                                        row_has_error = true;
                                        emitter.diag(RowDiagnostic {
                                            row: row.line,
                                            column: cr.diag_name.clone(),
                                            severity: Severity::Error,
                                            code: "invalid-language-tag".to_string(),
                                            message: e.0,
                                        });
                                        continue;
                                    }
                                }
                            } else if let Some(dt) = &ann.spec.datatype {
                                match resolve_iri_charged(dt, &ctx, emitter, row.line, rule_col) {
                                    Ok(dt_iri) => AnnotationValue::Literal(Literal::typed(
                                        val_str,
                                        dt_iri.as_str(),
                                    )),
                                    Err(ResolveError::Budget) => return Ok(()),
                                    Err(ResolveError::Invalid(msg)) => {
                                        ann_failed = true;
                                        row_has_error = true;
                                        emitter.diag(RowDiagnostic {
                                            row: row.line,
                                            column: cr.diag_name.clone(),
                                            severity: Severity::Error,
                                            code: "invalid-iri".to_string(),
                                            message: msg,
                                        });
                                        continue;
                                    }
                                }
                            } else {
                                AnnotationValue::Literal(Literal::simple(val_str))
                            };
                            ax.annotations.insert(Annotation {
                                property: AnnotationProperty(prop_iri.clone()),
                                value: ann_val,
                                annotations: Default::default(),
                            });
                        }
                    }

                    if !ann_failed {
                        row_axioms.push((ax, rule_col));
                    }
                }
            }

            if row_has_error {
                round_failed[row_i] = true;
                emitter.mark_row_error(row.line);
                continue;
            }
            match emitter.commit_row(row.line, row_declarations, row_axioms) {
                RowCommit::Committed => {}
                RowCommit::Invalid => {
                    round_failed[row_i] = true;
                }
                RowCommit::BudgetExceeded => return Ok(()),
            }
        }

        match convergence.advance(round, &round_contributed, &round_failed, &row_pass1_ok) {
            ConvergenceStep::Done => return Ok(()),
            ConvergenceStep::Continue => {}
            ConvergenceStep::LimitExceeded => {
                emitter.budget_error(
                    1,
                    None,
                    "vocab-dependency-limit",
                    format!(
                        "failed-row vocabulary dependency chain did not converge within {MAX_VOCAB_ROUNDS} passes"
                    ),
                );
                return Ok(());
            }
        }
    }
    Ok(())
}

fn split_values_bounded<'a>(
    cell: &'a str,
    sep: Option<&str>,
    max_values: usize,
) -> (Vec<&'a str>, bool) {
    if cell.is_empty() {
        return (Vec::new(), false);
    }
    match sep {
        Some(s) if !s.is_empty() => {
            let mut out = Vec::new();
            for v in cell.split(s).map(str::trim).filter(|v| !v.is_empty()) {
                if out.len() >= max_values {
                    return (out, true);
                }
                out.push(v);
            }
            (out, false)
        }
        _ => (vec![cell], false),
    }
}

enum RenderError {
    Row(String),
    Budget,
}

#[allow(clippy::too_many_arguments)]
fn render_segments_bounded(
    segments: &[Segment],
    bindings: &FxHashMap<&str, &str>,
    row: &super::TableRow,
    header_idx: &FxHashMap<&str, usize>,
    ctx: &Context,
    syntax: PatternSyntax,
    max_per_template: usize,
    emitter: &mut Emitter,
    line: usize,
    col_name: Option<&str>,
) -> Result<String, RenderError> {
    let mut out = String::new();
    let push_checked = |out: &mut String, piece: &str| -> Result<(), RenderError> {
        if out.len().saturating_add(piece.len()) > max_per_template {
            return Err(RenderError::Row(format!(
                "expanded template exceeds the {max_per_template} byte limit"
            )));
        }
        out.push_str(piece);
        Ok(())
    };

    for seg in segments {
        match seg {
            Segment::Literal(s) => push_checked(&mut out, s)?,
            Segment::Placeholder { column, filter } => {
                let raw = bindings
                    .get(column.as_str())
                    .copied()
                    .or_else(|| {
                        header_idx
                            .get(column.as_str())
                            .and_then(|&i| row.cells.get(i))
                            .map(|s| s.trim())
                    })
                    .unwrap_or("");
                match filter {
                    Filter::Raw => push_checked(&mut out, raw)?,
                    Filter::Iri => {
                        let iri = resolve_iri_charged(raw, ctx, emitter, line, col_name).map_err(
                            |e| match e {
                                ResolveError::Invalid(m) => RenderError::Row(m),
                                ResolveError::Budget => RenderError::Budget,
                            },
                        )?;
                        push_checked(&mut out, "<")?;
                        push_checked(&mut out, iri.as_str())?;
                        push_checked(&mut out, ">")?;
                    }
                    Filter::Slug => {
                        let slug = slugify(raw);
                        push_checked(&mut out, &slug)?;
                    }
                    Filter::Str => {
                        push_checked(&mut out, "\"")?;
                        escape_string_checked(raw, syntax, &mut out, max_per_template)?;
                        push_checked(&mut out, "\"")?;
                    }
                    Filter::Lang(tag) => {
                        push_checked(&mut out, "\"")?;
                        escape_string_checked(raw, syntax, &mut out, max_per_template)?;
                        push_checked(&mut out, "\"@")?;
                        push_checked(&mut out, tag)?;
                    }
                    Filter::Typed(dt) => {
                        let dt_iri = resolve_iri_charged(dt, ctx, emitter, line, col_name)
                            .map_err(|e| match e {
                                ResolveError::Invalid(m) => RenderError::Row(m),
                                ResolveError::Budget => RenderError::Budget,
                            })?;
                        push_checked(&mut out, "\"")?;
                        escape_string_checked(raw, syntax, &mut out, max_per_template)?;
                        push_checked(&mut out, "\"^^<")?;
                        push_checked(&mut out, dt_iri.as_str())?;
                        push_checked(&mut out, ">")?;
                    }
                }
            }
        }
    }
    if !emitter.charge_expanded_bytes(out.len(), line, col_name) {
        return Err(RenderError::Budget);
    }
    Ok(out)
}

/// Escape string literals according to the target OWL syntax:
/// - Functional-Style Syntax (`ofn_read`) escapes only `\` and `"`, preserving raw newlines
///   and tabs inside quoted strings.
/// - Manchester syntax escapes `\`, `"`, `\n`, `\r`, and `\t`.
fn escape_string_checked(
    s: &str,
    syntax: PatternSyntax,
    out: &mut String,
    max_per_template: usize,
) -> Result<(), RenderError> {
    for c in s.chars() {
        let extra = match (syntax, c) {
            (_, '\\' | '"') => 2,
            (PatternSyntax::Manchester, '\n' | '\r' | '\t') => 2,
            _ => c.len_utf8(),
        };
        if out.len().saturating_add(extra) > max_per_template {
            return Err(RenderError::Row(format!(
                "expanded template exceeds the {max_per_template} byte limit"
            )));
        }
        match (syntax, c) {
            (_, '\\') => out.push_str("\\\\"),
            (_, '"') => out.push_str("\\\""),
            (PatternSyntax::Manchester, '\n') => out.push_str("\\n"),
            (PatternSyntax::Manchester, '\r') => out.push_str("\\r"),
            (PatternSyntax::Manchester, '\t') => out.push_str("\\t"),
            (_, other) => out.push(other),
        }
    }
    Ok(())
}

fn slugify(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut prev_sep = false;
    for c in s.trim().chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
            prev_sep = false;
        } else if (c.is_whitespace() || c == '-' || c == '_' || c == '/')
            && !prev_sep
            && !out.is_empty()
        {
            out.push('_');
            prev_sep = true;
        }
    }
    while out.ends_with('_') {
        out.pop();
    }
    out
}

fn make_entity(iri: Iri, kind: EntityKind) -> Entity {
    match kind {
        EntityKind::Class => Entity::Class(Class(iri)),
        EntityKind::Datatype => Entity::Datatype(Datatype(iri)),
        EntityKind::ObjectProperty => Entity::ObjectProperty(ObjectProperty(iri)),
        EntityKind::DataProperty => Entity::DataProperty(DataProperty(iri)),
        EntityKind::AnnotationProperty => Entity::AnnotationProperty(AnnotationProperty(iri)),
        EntityKind::NamedIndividual => Entity::NamedIndividual(NamedIndividual(iri)),
    }
}
