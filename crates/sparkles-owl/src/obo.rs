#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct Qualifier {
    key: String,
    value: String,
}

#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct PropertyValue {
    prop: String,
    val: PvValue,
    qualifiers: Vec<Qualifier>,
}

#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum PvValue {
    Iri(String),
    Literal(String, String), // (lexical, datatype_obo_id)
}

#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct SynonymEntry {
    text: String,
    scope: &'static str,
    synonym_type: Option<String>,
    xrefs: Vec<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct DefEntry {
    text: String,
    xrefs: Vec<String>,
}

#[derive(Default)]
struct TermStanza {
    id: String,
    names: Vec<String>,
    namespaces: Vec<String>,
    alt_ids: Vec<String>,
    defs: Vec<DefEntry>,
    comments: Vec<String>,
    subsets: Vec<String>,
    synonyms: Vec<SynonymEntry>,
    xrefs: Vec<String>,
    is_a: Vec<(String, Vec<Qualifier>)>,
    intersection_of: Vec<(Option<String>, String)>,
    has_intersection: bool,
    union_of: Vec<String>,
    has_union: bool,
    equivalent_to: Vec<(String, Vec<Qualifier>)>,
    disjoint_from: Vec<(String, Vec<Qualifier>)>,
    relationships: Vec<(String, String, Vec<Qualifier>)>,
    is_obsolete: bool,
    replaced_by: Vec<String>,
    consider: Vec<String>,
    property_values: Vec<PropertyValue>,
    created_by: Vec<String>,
    creation_date: Vec<String>,
}

