//! OBO Flat File Format 1.4 (`.obo`) writer and reader.
//!
//! [`write_document`] translates an OWL 2 ontology header and axioms into OBO 1.4
//! header tags and `[Term]`, `[Typedef]` and `[Instance]` stanzas, following the
//! OBO 1.4 specification and OWL-to-OBO mapping conventions used by ROBOT and
//! `owlapi-oboformat`. Output is deterministic: header tags, stanzas and stanza
//! tags are written in canonical OBO 1.4 order with proper OBO escaping.
//!
//! Axioms outside the OBO 1.4 fragment (such as arbitrary complex class expressions,
//! `DisjointUnion`, `HasKey`, `DatatypeDefinition`, negative assertions, anonymous
//! individuals, inverse-property expressions, chains longer than two or duplicate
//! `intersection_of`/`union_of` definitions on one term) are either refused
//! ([`WriteOptions::strict`]) or skipped and recorded in [`WriteReport`].
//!
//! [`parse`] reads an OBO 1.4 document back into an [`crate::ofn_read::Document`].

