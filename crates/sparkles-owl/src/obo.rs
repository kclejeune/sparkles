// ------------------------------------------------------------------ reading ------

type RawStanza = (String, usize, Vec<(usize, String, String)>);

/// Read an OBO 1.4 (`.obo`) document into an [`crate::ofn_read::Document`].
pub fn parse(text: &str) -> Result<Document, ParseError> {
    let mut header = Header::default();
    let mut idspaces: FxHashMap<String, String> = FxHashMap::default();
    let mut declared_prefixes: Vec<(String, String)> = Vec::new();
    let mut stanzas: Vec<RawStanza> = Vec::new();
    let mut cur_stanza: Option<RawStanza> = None;

    for (idx, raw_line) in text.lines().enumerate() {
        let line_no = idx + 1;
        let line = strip_obo_comment(raw_line).trim();
        if line.is_empty() {
            continue;
        }
        if line.starts_with('[') && line.ends_with(']') {
            if let Some(prev) = cur_stanza.take() {
                stanzas.push(prev);
            }
            let kind = line[1..line.len() - 1].trim().to_string();
            cur_stanza = Some((kind, line_no, Vec::new()));
            continue;
        }
        let Some((tag, val)) = line.split_once(':') else {
            return Err(ParseError {
                line: line_no,
                column: 1,
                message: format!("expected 'tag: value' line, found '{line}'"),
            });
        };
        let tag = tag.trim().to_string();
        let val = val.trim().to_string();
        if let Some((_, _, ref mut tags)) = cur_stanza {
            tags.push((line_no, tag, val));
        } else {
            // Header tag
            match tag.as_str() {
                "format-version" => {}
                "idspace" => {
                    let mut parts = val.split_whitespace();
                    let Some(p) = parts.next() else {
                        return Err(perr(line_no, "idspace missing prefix"));
                    };
                    let Some(ns) = parts.next() else {
                        return Err(perr(line_no, "idspace missing namespace IRI"));
                    };
                    idspaces.insert(p.to_string(), ns.to_string());
                    declared_prefixes.push((p.to_string(), ns.to_string()));
                }
                "ontology" => {
                    let iri = expand_ontology_id(&val).map_err(|e| perr(line_no, e))?;
                    header.iri = Some(iri);
                }
                "data-version" => {
                    if let Ok(iri) = parse_iri(&val) {
                        header.version_iri = Some(iri);
                    } else {
                        header.annotations.insert(Annotation::new(
                            AnnotationProperty::new(vocab::OWL_VERSION_INFO),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&val))),
                        ));
                    }
                }
                "import" => {
                    let iri = parse_iri(&val).map_err(|e| perr(line_no, e.0))?;
                    header.imports.insert(iri);
                }
                "date" => {
                    header.annotations.insert(Annotation::new(
                        AnnotationProperty::new(OIO_DATE),
                        AnnotationValue::Literal(Literal::simple(unescape_obo(&val))),
                    ));
                }
                "saved-by" => {
                    header.annotations.insert(Annotation::new(
                        AnnotationProperty::new(OIO_SAVED_BY),
                        AnnotationValue::Literal(Literal::simple(unescape_obo(&val))),
                    ));
                }
                "auto-generated-by" => {
                    header.annotations.insert(Annotation::new(
                        AnnotationProperty::new(OIO_AUTO_GENERATED_BY),
                        AnnotationValue::Literal(Literal::simple(unescape_obo(&val))),
                    ));
                }
                "default-namespace" => {
                    header.annotations.insert(Annotation::new(
                        AnnotationProperty::new(OIO_DEFAULT_NAMESPACE),
                        AnnotationValue::Literal(Literal::simple(unescape_obo(&val))),
                    ));
                }
                "remark" => {
                    header
                        .annotations
                        .insert(Annotation::comment(&unescape_obo(&val)));
                }
                "property_value" => {
                    let (prop, aval, anns) =
                        parse_property_value(&val, &idspaces).map_err(|e| perr(line_no, e))?;
                    header.annotations.insert(Annotation {
                        property: prop,
                        value: aval,
                        annotations: anns,
                    });
                }
                _ => {}
            }
        }
    }
    if let Some(last) = cur_stanza {
        stanzas.push(last);
    }

    let mut axioms = Vec::new();
    for (kind, sline, tags) in stanzas {
        let Some((_, _, raw_id)) = tags.iter().find(|(_, t, _)| t == "id") else {
            return Err(perr(sline, format!("[{kind}] stanza missing id:")));
        };
        let iri = obo_id_to_iri(raw_id, &idspaces).map_err(|e| perr(sline, e))?;
        match kind.as_str() {
            "Term" => {
                let c = Class(iri.clone());
                axioms.push(Axiom::declaration(Entity::Class(c.clone())));
                let mut intersections: BTreeSet<ClassExpression> = BTreeSet::new();
                let mut unions: BTreeSet<ClassExpression> = BTreeSet::new();
                for (lno, tag, val) in tags {
                    let (body, quals) = split_qualifiers(&val).map_err(|e| perr(lno, e))?;
                    let anns = parse_qualifiers(&quals, &idspaces).map_err(|e| perr(lno, e))?;
                    match tag.as_str() {
                        "id" => {}
                        "name" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(vocab::RDFS_LABEL),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "namespace" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(OIO_HAS_OBO_NAMESPACE),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "alt_id" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(OIO_HAS_ALT_ID),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "comment" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(vocab::RDFS_COMMENT),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "subset" => {
                            let sub_iri =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                                AnnotationProperty::new(OIO_IN_SUBSET),
                                AnnotationSubject::Iri(iri.clone()),
                                AnnotationValue::Iri(sub_iri),
                            )));
                        }
                        "xref" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(OIO_HAS_DBXREF),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "def" => {
                            let (txt, xrefs) =
                                parse_quoted_and_xrefs(&body).map_err(|e| perr(lno, e))?;
                            let mut a = BTreeSet::new();
                            for x in xrefs {
                                a.insert(Annotation::new(
                                    AnnotationProperty::new(OIO_HAS_DBXREF),
                                    AnnotationValue::Literal(Literal::simple(x)),
                                ));
                            }
                            axioms.push(Axiom {
                                kind: AxiomKind::AnnotationAssertion(
                                    AnnotationProperty::new(IAO_DEFINITION),
                                    AnnotationSubject::Iri(iri.clone()),
                                    AnnotationValue::Literal(Literal::simple(txt)),
                                ),
                                annotations: a,
                            });
                        }
                        "synonym" => {
                            let (txt, scope, syn_ty, xrefs) =
                                parse_synonym(&body, &idspaces).map_err(|e| perr(lno, e))?;
                            let prop = match scope.as_str() {
                                "EXACT" => OIO_HAS_EXACT_SYNONYM,
                                "BROAD" => OIO_HAS_BROAD_SYNONYM,
                                "NARROW" => OIO_HAS_NARROW_SYNONYM,
                                "RELATED" => OIO_HAS_RELATED_SYNONYM,
                                other => {
                                    return Err(perr(
                                        lno,
                                        format!("unknown synonym scope '{other}'"),
                                    ));
                                }
                            };
                            let mut a = BTreeSet::new();
                            for x in xrefs {
                                a.insert(Annotation::new(
                                    AnnotationProperty::new(OIO_HAS_DBXREF),
                                    AnnotationValue::Literal(Literal::simple(x)),
                                ));
                            }
                            if let Some(ty) = syn_ty {
                                a.insert(Annotation::new(
                                    AnnotationProperty::new(OIO_HAS_SYNONYM_TYPE),
                                    AnnotationValue::Iri(ty),
                                ));
                            }
                            axioms.push(Axiom {
                                kind: AxiomKind::AnnotationAssertion(
                                    AnnotationProperty::new(prop),
                                    AnnotationSubject::Iri(iri.clone()),
                                    AnnotationValue::Literal(Literal::simple(txt)),
                                ),
                                annotations: a,
                            });
                        }
                        "is_a" => {
                            let sup =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::SubClassOf(
                                    ClassExpression::Class(c.clone()),
                                    ClassExpression::Class(Class(sup)),
                                ),
                                annotations: anns,
                            });
                        }
                        "intersection_of" => {
                            let parts: Vec<&str> = body.split_whitespace().collect();
                            match parts.as_slice() {
                                [cls] => {
                                    let ci =
                                        obo_id_to_iri(cls, &idspaces).map_err(|e| perr(lno, e))?;
                                    intersections.insert(ClassExpression::Class(Class(ci)));
                                }
                                [rel, cls] => {
                                    let ri =
                                        obo_id_to_iri(rel, &idspaces).map_err(|e| perr(lno, e))?;
                                    let ci =
                                        obo_id_to_iri(cls, &idspaces).map_err(|e| perr(lno, e))?;
                                    intersections.insert(ClassExpression::some(
                                        ObjectProperty(ri),
                                        Class(ci),
                                    ));
                                }
                                _ => {
                                    return Err(perr(
                                        lno,
                                        format!("invalid intersection_of value '{body}'"),
                                    ));
                                }
                            }
                        }
                        "union_of" => {
                            let ci =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            unions.insert(ClassExpression::Class(Class(ci)));
                        }
                        "equivalent_to" => {
                            let other =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            let mut set = BTreeSet::new();
                            set.insert(ClassExpression::Class(c.clone()));
                            set.insert(ClassExpression::Class(Class(other)));
                            axioms.push(Axiom {
                                kind: AxiomKind::EquivalentClasses(set),
                                annotations: anns,
                            });
                        }
                        "disjoint_from" => {
                            let other =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::DisjointClasses(
                                    vec![
                                        ClassExpression::Class(c.clone()),
                                        ClassExpression::Class(Class(other)),
                                    ]
                                    .into(),
                                ),
                                annotations: anns,
                            });
                        }
                        "relationship" => {
                            let mut parts = body.split_whitespace();
                            let (Some(rel), Some(target)) = (parts.next(), parts.next()) else {
                                return Err(perr(lno, format!("invalid relationship '{body}'")));
                            };
                            let ri = obo_id_to_iri(rel, &idspaces).map_err(|e| perr(lno, e))?;
                            let ti = obo_id_to_iri(target, &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::SubClassOf(
                                    ClassExpression::Class(c.clone()),
                                    ClassExpression::some(ObjectProperty(ri), Class(ti)),
                                ),
                                annotations: anns,
                            });
                        }
                        "is_obsolete" if body.trim() == "true" => {
                            axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                                AnnotationProperty::new(vocab::OWL_DEPRECATED),
                                AnnotationSubject::Iri(iri.clone()),
                                AnnotationValue::Literal(Literal::typed(
                                    "true",
                                    vocab::XSD_BOOLEAN,
                                )),
                            )));
                        }
                        "replaced_by" => {
                            let ti =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                                AnnotationProperty::new(IAO_REPLACED_BY),
                                AnnotationSubject::Iri(iri.clone()),
                                AnnotationValue::Iri(ti),
                            )));
                        }
                        "consider" => {
                            let ti =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                                AnnotationProperty::new(OIO_CONSIDER),
                                AnnotationSubject::Iri(iri.clone()),
                                AnnotationValue::Iri(ti),
                            )));
                        }
                        "created_by" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(OIO_CREATED_BY),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "creation_date" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(OIO_CREATION_DATE),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "property_value" => {
                            let (prop, aval, pv_anns) =
                                parse_property_value(&val, &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::AnnotationAssertion(
                                    prop,
                                    AnnotationSubject::Iri(iri.clone()),
                                    aval,
                                ),
                                annotations: pv_anns,
                            });
                        }
                        _ => {}
                    }
                }
                if !intersections.is_empty() {
                    let mut set = BTreeSet::new();
                    set.insert(ClassExpression::Class(c.clone()));
                    set.insert(ClassExpression::ObjectIntersectionOf(intersections));
                    axioms.push(Axiom::new(AxiomKind::EquivalentClasses(set)));
                }
                if !unions.is_empty() {
                    let mut set = BTreeSet::new();
                    set.insert(ClassExpression::Class(c));
                    set.insert(ClassExpression::ObjectUnionOf(unions));
                    axioms.push(Axiom::new(AxiomKind::EquivalentClasses(set)));
                }
            }
            "Typedef" => {
                let is_meta = tags
                    .iter()
                    .any(|(_, t, v)| t == "is_metadata_tag" && v.trim() == "true");
                if is_meta {
                    axioms.push(Axiom::declaration(Entity::AnnotationProperty(
                        AnnotationProperty(iri.clone()),
                    )));
                } else {
                    axioms.push(Axiom::declaration(Entity::ObjectProperty(ObjectProperty(
                        iri.clone(),
                    ))));
                }
                for (lno, tag, val) in tags {
                    let (body, quals) = split_qualifiers(&val).map_err(|e| perr(lno, e))?;
                    let anns = parse_qualifiers(&quals, &idspaces).map_err(|e| perr(lno, e))?;
                    match tag.as_str() {
                        "id" | "is_metadata_tag" => {}
                        "name" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(vocab::RDFS_LABEL),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "namespace" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(OIO_HAS_OBO_NAMESPACE),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "comment" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(vocab::RDFS_COMMENT),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "def" => {
                            let (txt, xrefs) =
                                parse_quoted_and_xrefs(&body).map_err(|e| perr(lno, e))?;
                            let mut a = BTreeSet::new();
                            for x in xrefs {
                                a.insert(Annotation::new(
                                    AnnotationProperty::new(OIO_HAS_DBXREF),
                                    AnnotationValue::Literal(Literal::simple(x)),
                                ));
                            }
                            axioms.push(Axiom {
                                kind: AxiomKind::AnnotationAssertion(
                                    AnnotationProperty::new(IAO_DEFINITION),
                                    AnnotationSubject::Iri(iri.clone()),
                                    AnnotationValue::Literal(Literal::simple(txt)),
                                ),
                                annotations: a,
                            });
                        }
                        "xref" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(OIO_HAS_DBXREF),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "domain" => {
                            let d =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            if is_meta {
                                axioms.push(Axiom::new(AxiomKind::AnnotationPropertyDomain(
                                    AnnotationProperty(iri.clone()),
                                    d,
                                )));
                            } else {
                                axioms.push(Axiom::new(AxiomKind::ObjectPropertyDomain(
                                    ObjectProperty(iri.clone()).into(),
                                    ClassExpression::Class(Class(d)),
                                )));
                            }
                        }
                        "range" => {
                            let r =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            if is_meta {
                                axioms.push(Axiom::new(AxiomKind::AnnotationPropertyRange(
                                    AnnotationProperty(iri.clone()),
                                    r,
                                )));
                            } else {
                                axioms.push(Axiom::new(AxiomKind::ObjectPropertyRange(
                                    ObjectProperty(iri.clone()).into(),
                                    ClassExpression::Class(Class(r)),
                                )));
                            }
                        }
                        "is_anti_symmetric" if body.trim() == "true" => {
                            axioms.push(Axiom::new(AxiomKind::AsymmetricObjectProperty(
                                ObjectProperty(iri.clone()).into(),
                            )));
                        }
                        "is_reflexive" if body.trim() == "true" => {
                            axioms.push(Axiom::new(AxiomKind::ReflexiveObjectProperty(
                                ObjectProperty(iri.clone()).into(),
                            )));
                        }
                        "is_symmetric" if body.trim() == "true" => {
                            axioms.push(Axiom::new(AxiomKind::SymmetricObjectProperty(
                                ObjectProperty(iri.clone()).into(),
                            )));
                        }
                        "is_transitive" if body.trim() == "true" => {
                            axioms.push(Axiom::new(AxiomKind::TransitiveObjectProperty(
                                ObjectProperty(iri.clone()).into(),
                            )));
                        }
                        "is_functional" if body.trim() == "true" => {
                            axioms.push(Axiom::new(AxiomKind::FunctionalObjectProperty(
                                ObjectProperty(iri.clone()).into(),
                            )));
                        }
                        "is_inverse_functional" if body.trim() == "true" => {
                            axioms.push(Axiom::new(AxiomKind::InverseFunctionalObjectProperty(
                                ObjectProperty(iri.clone()).into(),
                            )));
                        }
                        "is_a" => {
                            let sup =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            let kind = if is_meta {
                                AxiomKind::SubAnnotationPropertyOf(
                                    AnnotationProperty(iri.clone()),
                                    AnnotationProperty(sup),
                                )
                            } else {
                                AxiomKind::SubObjectPropertyOf(
                                    SubObjectPropertyExpression::Expression(
                                        ObjectProperty(iri.clone()).into(),
                                    ),
                                    ObjectProperty(sup).into(),
                                )
                            };
                            axioms.push(Axiom {
                                kind,
                                annotations: anns,
                            });
                        }
                        "equivalent_to" => {
                            let other =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            let mut set = BTreeSet::new();
                            set.insert(ObjectPropertyExpression::Property(ObjectProperty(
                                iri.clone(),
                            )));
                            set.insert(ObjectPropertyExpression::Property(ObjectProperty(other)));
                            axioms.push(Axiom {
                                kind: AxiomKind::EquivalentObjectProperties(set),
                                annotations: anns,
                            });
                        }
                        "disjoint_from" => {
                            let other =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::DisjointObjectProperties(
                                    vec![
                                        ObjectPropertyExpression::Property(ObjectProperty(
                                            iri.clone(),
                                        )),
                                        ObjectPropertyExpression::Property(ObjectProperty(other)),
                                    ]
                                    .into(),
                                ),
                                annotations: anns,
                            });
                        }
                        "inverse_of" => {
                            let other =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::InverseObjectProperties(
                                    ObjectProperty(iri.clone()).into(),
                                    ObjectProperty(other).into(),
                                ),
                                annotations: anns,
                            });
                        }
                        "holds_over_chain" => {
                            let parts: Vec<&str> = body.split_whitespace().collect();
                            if parts.len() != 2 {
                                return Err(perr(
                                    lno,
                                    format!("invalid holds_over_chain '{body}'"),
                                ));
                            }
                            let p1 =
                                obo_id_to_iri(parts[0], &idspaces).map_err(|e| perr(lno, e))?;
                            let p2 =
                                obo_id_to_iri(parts[1], &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::SubObjectPropertyOf(
                                    SubObjectPropertyExpression::Chain(vec![
                                        ObjectProperty(p1).into(),
                                        ObjectProperty(p2).into(),
                                    ]),
                                    ObjectProperty(iri.clone()).into(),
                                ),
                                annotations: anns,
                            });
                        }
                        "is_obsolete" if body.trim() == "true" => {
                            axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                                AnnotationProperty::new(vocab::OWL_DEPRECATED),
                                AnnotationSubject::Iri(iri.clone()),
                                AnnotationValue::Literal(Literal::typed(
                                    "true",
                                    vocab::XSD_BOOLEAN,
                                )),
                            )));
                        }
                        "property_value" => {
                            let (prop, aval, pv_anns) =
                                parse_property_value(&val, &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::AnnotationAssertion(
                                    prop,
                                    AnnotationSubject::Iri(iri.clone()),
                                    aval,
                                ),
                                annotations: pv_anns,
                            });
                        }
                        _ => {}
                    }
                }
            }
            "Instance" => {
                let ind = NamedIndividual(iri.clone());
                axioms.push(Axiom::declaration(Entity::NamedIndividual(ind.clone())));
                for (lno, tag, val) in tags {
                    let (body, quals) = split_qualifiers(&val).map_err(|e| perr(lno, e))?;
                    let anns = parse_qualifiers(&quals, &idspaces).map_err(|e| perr(lno, e))?;
                    match tag.as_str() {
                        "id" => {}
                        "name" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(vocab::RDFS_LABEL),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "namespace" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(OIO_HAS_OBO_NAMESPACE),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "comment" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(vocab::RDFS_COMMENT),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "xref" => axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                            AnnotationProperty::new(OIO_HAS_DBXREF),
                            AnnotationSubject::Iri(iri.clone()),
                            AnnotationValue::Literal(Literal::simple(unescape_obo(&body))),
                        ))),
                        "instance_of" => {
                            let ci =
                                obo_id_to_iri(body.trim(), &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::ClassAssertion(
                                    ClassExpression::Class(Class(ci)),
                                    Individual::Named(ind.clone()),
                                ),
                                annotations: anns,
                            });
                        }
                        "relationship" => {
                            let mut parts = body.split_whitespace();
                            let (Some(rel), Some(target)) = (parts.next(), parts.next()) else {
                                return Err(perr(lno, format!("invalid relationship '{body}'")));
                            };
                            let ri = obo_id_to_iri(rel, &idspaces).map_err(|e| perr(lno, e))?;
                            let ti = obo_id_to_iri(target, &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::ObjectPropertyAssertion(
                                    ObjectProperty(ri).into(),
                                    Individual::Named(ind.clone()),
                                    Individual::Named(NamedIndividual(ti)),
                                ),
                                annotations: anns,
                            });
                        }
                        "is_obsolete" if body.trim() == "true" => {
                            axioms.push(Axiom::new(AxiomKind::AnnotationAssertion(
                                AnnotationProperty::new(vocab::OWL_DEPRECATED),
                                AnnotationSubject::Iri(iri.clone()),
                                AnnotationValue::Literal(Literal::typed(
                                    "true",
                                    vocab::XSD_BOOLEAN,
                                )),
                            )));
                        }
                        "property_value" => {
                            let (prop, aval, pv_anns) =
                                parse_property_value(&val, &idspaces).map_err(|e| perr(lno, e))?;
                            axioms.push(Axiom {
                                kind: AxiomKind::AnnotationAssertion(
                                    prop,
                                    AnnotationSubject::Iri(iri.clone()),
                                    aval,
                                ),
                                annotations: pv_anns,
                            });
                        }
                        _ => {}
                    }
                }
            }
            other => return Err(perr(sline, format!("unknown OBO stanza '[{other}]'"))),
        }
    }

    for ax in &axioms {
        validate::axiom(ax).map_err(|e| perr(1, e.0))?;
    }

    Ok(Document {
        prefixes: declared_prefixes,
        header,
        axioms,
        rules: 0,
    })
}

fn perr(line: usize, message: impl Into<String>) -> ParseError {
    ParseError {
        line,
        column: 1,
        message: message.into(),
    }
}

/// Strip an unescaped `!` comment outside double-quoted strings.
fn strip_obo_comment(line: &str) -> &str {
    let mut in_quote = false;
    let mut escaped = false;
    for (i, c) in line.char_indices() {
        if escaped {
            escaped = false;
            continue;
        }
        match c {
            '\\' => escaped = true,
            '"' => in_quote = !in_quote,
            '!' if !in_quote => return &line[..i],
            _ => {}
        }
    }
    line
}

/// Split trailing `{k="v", ...}` qualifiers from an OBO tag value.
fn split_qualifiers(val: &str) -> Result<(String, Option<String>), String> {
    let trimmed = val.trim_end();
    if !trimmed.ends_with('}') {
        return Ok((val.to_string(), None));
    }
    // Walk forward tracking quotes & escapes to find the matching unescaped `{`.
    let mut in_quote = false;
    let mut escaped = false;
    let mut brace_start = None;
    for (i, c) in trimmed.char_indices() {
        if escaped {
            escaped = false;
            continue;
        }
        match c {
            '\\' => escaped = true,
            '"' => in_quote = !in_quote,
            '{' if !in_quote => brace_start = Some(i),
            _ => {}
        }
    }
    let Some(start) = brace_start else {
        return Ok((val.to_string(), None));
    };
    let before = trimmed[..start].trim_end().to_string();
    let inside = trimmed[start + 1..trimmed.len() - 1].trim().to_string();
    Ok((before, Some(inside)))
}

fn parse_qualifiers(
    raw: &Option<String>,
    idspaces: &FxHashMap<String, String>,
) -> Result<BTreeSet<Annotation>, String> {
    let mut out = BTreeSet::new();
    let Some(s) = raw else {
        return Ok(out);
    };
    let mut rest = s.trim();
    while !rest.is_empty() {
        let eq = rest
            .find('=')
            .ok_or_else(|| format!("expected '=' in OBO qualifier '{rest}'"))?;
        let key = rest[..eq].trim();
        let after_eq = rest[eq + 1..].trim_start();
        let (val, consumed) = parse_obo_quoted(after_eq)?;
        let prop = if key == "is_inferred" {
            AnnotationProperty::new(OIO_IS_INFERRED)
        } else {
            AnnotationProperty(obo_id_to_iri(key, idspaces)?)
        };
        out.insert(Annotation::new(
            prop,
            AnnotationValue::Literal(Literal::simple(val)),
        ));
        rest = after_eq[consumed..].trim_start();
        if let Some(r) = rest.strip_prefix(',') {
            rest = r.trim_start();
        }
    }
    Ok(out)
}

fn parse_obo_quoted(s: &str) -> Result<(String, usize), String> {
    if !s.starts_with('"') {
        return Err(format!("expected quoted string at '{s}'"));
    }
    let mut out = String::new();
    let mut chars = s[1..].char_indices();
    while let Some((idx, c)) = chars.next() {
        if c == '"' {
            return Ok((out, idx + 2));
        }
        if c == '\\' {
            match chars.next() {
                Some((_, 'n')) => out.push('\n'),
                Some((_, 't')) => out.push('\t'),
                Some((_, other)) => out.push(other),
                None => return Err("unterminated escape in quoted string".into()),
            }
        } else {
            out.push(c);
        }
    }
    Err("unterminated quoted string".into())
}

fn parse_xref_list(s: &str) -> Result<Vec<String>, String> {
    let s = s.trim();
    let inner = s
        .strip_prefix('[')
        .and_then(|r| r.strip_suffix(']'))
        .ok_or_else(|| format!("expected [...] xref list, found '{s}'"))?
        .trim();
    if inner.is_empty() {
        return Ok(Vec::new());
    }
    Ok(inner
        .split(',')
        .map(|x| unescape_obo(x.trim()))
        .filter(|x| !x.is_empty())
        .collect())
}

fn parse_quoted_and_xrefs(s: &str) -> Result<(String, Vec<String>), String> {
    let (txt, consumed) = parse_obo_quoted(s.trim_start())?;
    let rest = s.trim_start()[consumed..].trim();
    let xrefs = if rest.is_empty() {
        Vec::new()
    } else {
        parse_xref_list(rest)?
    };
    Ok((txt, xrefs))
}

fn parse_synonym(
    s: &str,
    idspaces: &FxHashMap<String, String>,
) -> Result<(String, String, Option<Iri>, Vec<String>), String> {
    let trimmed = s.trim_start();
    let (txt, consumed) = parse_obo_quoted(trimmed)?;
    let rest = trimmed[consumed..].trim();
    let bracket = rest
        .find('[')
        .ok_or_else(|| format!("synonym missing [...] xref list: '{s}'"))?;
    let middle = rest[..bracket].trim();
    let xrefs = parse_xref_list(&rest[bracket..])?;
    let mut parts = middle.split_whitespace();
    let scope = parts
        .next()
        .ok_or_else(|| format!("synonym missing scope: '{s}'"))?
        .to_string();
    let syn_ty = match parts.next() {
        Some(t) => Some(obo_id_to_iri(t, idspaces)?),
        None => None,
    };
    Ok((txt, scope, syn_ty, xrefs))
}

fn parse_property_value(
    val: &str,
    idspaces: &FxHashMap<String, String>,
) -> Result<(AnnotationProperty, AnnotationValue, BTreeSet<Annotation>), String> {
    let (body, quals) = split_qualifiers(val)?;
    let anns = parse_qualifiers(&quals, idspaces)?;
    let body = body.trim();
    let Some((prop_str, rest)) = body.split_once(char::is_whitespace) else {
        return Err(format!("invalid property_value '{body}'"));
    };
    let prop = AnnotationProperty(obo_id_to_iri(prop_str.trim(), idspaces)?);
    let rest = rest.trim();
    if rest.starts_with('"') {
        let (lex, consumed) = parse_obo_quoted(rest)?;
        let dt_str = rest[consumed..].trim();
        let lit = if dt_str.is_empty() {
            Literal::simple(lex)
        } else {
            let dt = obo_id_to_iri(dt_str, idspaces)?;
            Literal::typed(lex, dt.as_str())
        };
        Ok((prop, AnnotationValue::Literal(lit), anns))
    } else {
        let iri = obo_id_to_iri(rest, idspaces)?;
        Ok((prop, AnnotationValue::Iri(iri), anns))
    }
}
